//! Xiaomi MiMo browser authorization with encrypted loopback credential delivery.
//! 通过回环加密交付凭据的小米 MiMo 浏览器授权。

use super::*;
use crate::{BrowserCallbackSecretProjection, xiaomi::MiMoService};
use ring::{aead, agreement, rand::SystemRandom};

/// Official origin serving the authorization page and delivering the encrypted key.
/// 提供授权页并交付加密密钥的官方来源。
const ORIGIN: &str = "https://platform.xiaomimimo.com";
/// Callback path emitted by the official page for localhost redirects.
/// 官方页面在本地主机跳转时使用的回调路径。
const CALLBACK_PATH: &str = "/auth";
/// Lifetime of a single MiMo Code browser attempt.
/// MiMo Code 单次浏览器授权的有效时间。
const CALLBACK_LIFETIME: Duration = Duration::from_secs(300);
/// DER SubjectPublicKeyInfo prefix for a 32-byte X25519 public key.
/// 32 字节 X25519 公钥的 DER SubjectPublicKeyInfo 前缀。
const X25519_SPKI_PREFIX: &[u8] = b"\x30\x2a\x30\x05\x06\x03\x2b\x65\x6e\x03\x21\x00";
/// Length of the raw X25519 public key prefixed to the encrypted payload.
/// 加密载荷前置的 X25519 原始公钥长度。
const X25519_PUBLIC_KEY_BYTES: usize = 32;

/// Exact credential payload generated by the MiMo authorization page.
/// MiMo 授权页面生成的精确凭据载荷。
#[derive(Deserialize)]
struct AuthorizedKey {
    /// Newly authorized API key.
    /// 新授权的 API Key。
    sk: String,
    /// Stable MiMo account identifier.
    /// 稳定的 MiMo 账号标识。
    uid: String,
    /// Selected official service URL, including the protocol path.
    /// 选中的官方服务地址，包含协议路径。
    url: String,
}

impl OAuthAuthorizationRuntime {
    /// Starts MiMo's official localhost flow and returns a secret-free browser challenge.
    /// 启动 MiMo 官方本地主机流程并返回不含秘密的浏览器挑战。
    /// `binding` freezes the selected profile, and `service_base_url` pins the key's destination.
    /// `binding` 冻结所选凭据档，`service_base_url` 固定密钥的目的地。
    pub(super) async fn start_xiaomi_mimo(
        &self,
        binding: String,
        service_base_url: &str,
    ) -> Result<OAuthAuthorizationChallenge, String> {
        // service fixes the product and key type before the browser can return a credential.
        // service 在浏览器返回凭据前固定产品及密钥类型。
        let service = MiMoService::for_base_url(service_base_url)?;
        // listener only accepts IPv4 loopback traffic while the official URL uses localhost.
        // listener 仅接受 IPv4 回环流量，官方地址仍使用 localhost。
        let listener = TcpListener::bind("127.0.0.1:0")
            .await
            .map_err(|_| String::from("Could not bind the Xiaomi MiMo loopback listener."))?;
        // port ties the callback to this transaction's reserved socket.
        // port 将回调绑定到本事务保留的套接字。
        let port = listener
            .local_addr()
            .map_err(|_| String::from("Could not inspect the Xiaomi MiMo loopback listener."))?
            .port();
        // callback_authority must match the Host sent by the official browser callback.
        // callback_authority 必须匹配官方浏览器回调发送的 Host。
        let callback_authority = format!("localhost:{port}");
        // private_key is unique to this transaction and consumed by the encrypted exchange.
        // private_key 专属于本事务，由加密交换一次性消耗。
        let private_key =
            agreement::EphemeralPrivateKey::generate(&agreement::X25519, &SystemRandom::new())
                .map_err(|_| {
                    String::from("Could not generate the Xiaomi MiMo authorization key.")
                })?;
        // public_key exposes only the ephemeral X25519 public component to the platform.
        // public_key 只向平台公开临时 X25519 公钥部分。
        let public_key = private_key.compute_public_key().map_err(|_| {
            String::from("Could not derive the Xiaomi MiMo authorization public key.")
        })?;
        // encoded_key wraps the raw public key in the platform's expected SPKI encoding.
        // encoded_key 将原始公钥封装为平台要求的 SPKI 编码。
        let encoded_key =
            URL_SAFE_NO_PAD.encode([X25519_SPKI_PREFIX, public_key.as_ref()].concat());
        // key_name identifies the platform-issued key without any account or device identifier.
        // key_name 标识平台签发的密钥，不含任何账号或设备标识。
        let key_name = format!("vulcan-code-{}", Uuid::new_v4().simple());
        // authorization_url contains the public authorization inputs only.
        // authorization_url 仅包含公开的授权输入。
        let mut authorization_url = Url::parse(&format!("{ORIGIN}/authorize"))
            .map_err(|_| String::from("Xiaomi MiMo authorization URL is invalid."))?;
        authorization_url
            .query_pairs_mut()
            .append_pair("pk", &encoded_key)
            .append_pair("redirect_uri", &format!("http://{callback_authority}/"))
            .append_pair("kn", "mimocode")
            .append_pair("app", "Vulcan Code")
            .append_pair("key_name", &key_name);
        // snapshot carries the process-local binding and the single authorization deadline.
        // snapshot 携带进程内绑定及唯一授权截止时间。
        let snapshot = OAuthTransactionSnapshot {
            transaction_id: format!("auth_{}", Uuid::new_v4().simple()),
            authorization_binding: binding,
            phase: OAuthTransactionPhase::WaitingForCallback,
            expires_at_unix_ms: unix_millis()?
                .checked_add(CALLBACK_LIFETIME.as_millis() as u64)
                .ok_or_else(|| String::from("Xiaomi MiMo authorization expiration overflowed."))?,
            message: None,
        };
        // Owned task inputs preserve the service route and registration identity.
        // 任务持有的输入保留服务路由和注册身份。
        let service_base_url = service_base_url.to_owned();
        // transactions shares the host's cancellation and completion state.
        // transactions 共享宿主的取消和完成状态。
        let transactions = Arc::clone(&self.transactions);
        // transaction_id pins completion to the registered attempt.
        // transaction_id 将完成事件固定到已注册的尝试。
        let transaction_id = snapshot.transaction_id.clone();
        // The gate prevents completion before the shared runtime records the task.
        // 此门闩防止任务在共享运行时登记之前完成。
        let (sender, receiver) = oneshot::channel();
        // task owns the private key and is aborted through the shared runtime.
        // task 持有私钥，并由共享运行时中止。
        let task = tokio::spawn(async move {
            if receiver.await.is_err() {
                return;
            }
            // One deadline covers connection, bounded header reads, and credential delivery.
            // 同一截止时间覆盖连接、受限请求头读取和凭据交付。
            let result = timeout(
                CALLBACK_LIFETIME,
                receive_key(
                    listener,
                    &callback_authority,
                    private_key,
                    service,
                    &service_base_url,
                    key_name,
                ),
            )
            .await
            .unwrap_or_else(|_| Err(String::from("Xiaomi MiMo browser authorization expired.")));
            finish_transaction(transactions, &transaction_id, result).await;
        });
        self.register_transaction(&snapshot.transaction_id, snapshot.clone(), &task)
            .await?;
        if sender.send(()).is_err() {
            self.transactions
                .lock()
                .await
                .remove(&snapshot.transaction_id);
            return Err(String::from(
                "Xiaomi MiMo authorization stopped before registration.",
            ));
        }
        Ok(OAuthAuthorizationChallenge {
            transaction: snapshot,
            authorization_url: authorization_url.to_string(),
            flow_kind: OAuthAuthorizationFlowKind::LoopbackCallback,
            user_code: None,
            poll_interval_ms: None,
        })
    }
}

/// Reads the first matching official callback and returns the validated static credential.
/// 读取首个匹配的官方回调并返回校验后的静态凭据。
/// The listener and authority own the loopback route; the key, service, URL and label are transaction inputs.
/// 监听器与 authority 持有回环路由；私钥、服务、地址与标签为事务输入。
async fn receive_key(
    listener: TcpListener,
    authority: &str,
    private_key: agreement::EphemeralPrivateKey,
    service: MiMoService,
    service_base_url: &str,
    key_name: String,
) -> Result<CredentialSecretMaterial, String> {
    loop {
        // stream is local and unrelated requests do not consume the transaction key.
        // stream 为本地连接，无关请求不会消耗事务私钥。
        let (mut stream, _) = listener
            .accept()
            .await
            .map_err(|_| String::from("Xiaomi MiMo callback listener stopped."))?;
        // headers uses the shared HTTP deadline so an idle local connection cannot hold the listener indefinitely.
        // headers 使用共享 HTTP 截止时间，避免空闲本地连接长期占用监听器。
        let Ok(Ok(headers)) = timeout(
            OAUTH_HTTP_REQUEST_TIMEOUT,
            read_callback_headers(&mut stream),
        )
        .await
        else {
            continue;
        };
        // encrypted contains the sole payload from the exact callback route.
        // encrypted 持有精确回调路由的唯一载荷。
        let Some(encrypted) = callback_payload(&headers, authority) else {
            continue;
        };
        // result reflects decryption and routing checks, independently of browser response delivery.
        // result 表示解密与路由检查结果，与浏览器响应投递独立。
        let result = decrypt_key(private_key, &encrypted)
            .and_then(|key| credential_material(key, service, service_base_url, key_name));
        let _ = timeout(
            OAUTH_HTTP_REQUEST_TIMEOUT,
            write_callback_response(&mut stream, callback_html(result.is_ok())),
        )
        .await;
        return result;
    }
}

/// Extracts a single encrypted payload from the expected localhost GET request.
/// 从预期的本地主机 GET 请求中提取唯一加密载荷。
/// `headers` are bounded bytes and `authority` is the reserved localhost address.
/// `headers` 为有界字节，`authority` 为已保留的本地主机地址。
fn callback_payload(headers: &[u8], authority: &str) -> Option<String> {
    // header_text excludes anything following the HTTP header terminator.
    // header_text 排除 HTTP 请求头结束符后的所有数据。
    let (header_text, _) = std::str::from_utf8(headers).ok()?.split_once("\r\n\r\n")?;
    // lines separates the request line from the Host and optional Origin headers.
    // lines 将请求行与 Host 和可选 Origin 请求头分离。
    let mut lines = header_text.lines();
    // request_target accepts browser GETs using the exact official path.
    // request_target 接受使用精确官方路径的浏览器 GET 请求。
    let request_target = lines.next()?.strip_prefix("GET ")?.split_once(' ')?.0;
    if request_target.split_once('?')?.0 != CALLBACK_PATH {
        return None;
    }
    // hosts enforces the loopback authority and rejects ambiguous duplicate Host fields.
    // hosts 强制使用回环授权端，并拒绝有歧义的重复 Host 字段。
    let mut hosts = lines.clone().filter_map(|line| {
        line.split_once(':')
            .filter(|(name, _)| name.eq_ignore_ascii_case("host"))
            .map(|(_, value)| value.trim())
    });
    if hosts.next() != Some(authority) || hosts.next().is_some() {
        return None;
    }
    if lines
        .filter_map(|line| line.split_once(':'))
        .any(|(name, value)| name.eq_ignore_ascii_case("origin") && value.trim() != ORIGIN)
    {
        return None;
    }
    // url decodes the official query parameter without returning the full callback URL.
    // url 解码官方查询参数且不返回完整回调地址。
    let url = Url::parse(&format!("http://{authority}{request_target}")).ok()?;
    // params rejects ambiguous payload parameters instead of choosing one of them.
    // params 拒绝含糊的载荷参数，而不从中任选一个。
    let mut params = url.query_pairs();
    // encrypted is the ephemeral-key-bound sealed message.
    // encrypted 为绑定临时密钥的密封消息。
    let (name, encrypted) = params.next()?;
    (name == "u" && !encrypted.is_empty() && params.next().is_none())
        .then(|| encrypted.into_owned())
}

/// Decrypts MiMo's public-key, nonce, ciphertext and tag envelope with the transaction key.
/// 用事务私钥解密 MiMo 由公钥、随机数、密文和认证标签构成的信封。
/// `encoded` is unpadded base64url; returns authenticated JSON or a sanitized error.
/// `encoded` 为无填充的 base64url；返回已认证的 JSON 或脱敏错误。
fn decrypt_key(
    private_key: agreement::EphemeralPrivateKey,
    encoded: &str,
) -> Result<AuthorizedKey, String> {
    // failure avoids exposing the encrypted or decrypted credential in diagnostics.
    // failure 避免在诊断中暴露加密或解密后的凭据。
    let failure = || String::from("Xiaomi MiMo authorization payload could not be decrypted.");
    // envelope holds the binary response in the order used by MiMo Code.
    // envelope 按 MiMo Code 使用的顺序保存二进制响应。
    let mut envelope = URL_SAFE_NO_PAD.decode(encoded).map_err(|_| failure())?;
    // peer_bytes and sealed split the raw X25519 key from the AES-GCM envelope.
    // peer_bytes 与 sealed 将 X25519 原始公钥从 AES-GCM 信封中分离。
    let (peer_bytes, sealed) = envelope
        .split_at_mut_checked(X25519_PUBLIC_KEY_BYTES)
        .ok_or_else(failure)?;
    // nonce_bytes and ciphertext split the nonce from the ciphertext and trailing GCM tag.
    // nonce_bytes 与 ciphertext 分离随机数、密文及其尾部的 GCM 认证标签。
    let (nonce_bytes, ciphertext) = sealed
        .split_at_mut_checked(aead::NONCE_LEN)
        .ok_or_else(failure)?;
    // peer is the platform's per-response X25519 public key.
    // peer 为平台为单次响应生成的 X25519 公钥。
    let peer = agreement::UnparsedPublicKey::new(&agreement::X25519, peer_bytes);
    // key hashes the shared secret exactly as the upstream MiMo Code implementation does.
    // key 严格按上游 MiMo Code 实现散列共享秘密。
    let key = agreement::agree_ephemeral(private_key, &peer, |shared_secret| {
        aead::UnboundKey::new(&aead::AES_256_GCM, &Sha256::digest(shared_secret))
    })
    .map_err(|_| failure())?
    .map_err(|_| failure())?;
    // nonce consumes the official 12-byte nonce for this one-time exchange.
    // nonce 在本次一次性交换中使用官方定义的 12 字节随机数。
    let nonce = aead::Nonce::try_assume_unique_for_key(nonce_bytes).map_err(|_| failure())?;
    // plaintext becomes readable only after the GCM tag has been checked.
    // plaintext 仅在 GCM 标签通过检查后可读。
    let plaintext = aead::LessSafeKey::new(key)
        .open_in_place(nonce, aead::Aad::empty(), ciphertext)
        .map_err(|_| failure())?;
    serde_json::from_slice(plaintext)
        .map_err(|_| String::from("Xiaomi MiMo returned an invalid authorization payload."))
}

/// Projects an authenticated MiMo payload into the existing secure static authorization format.
/// 将已认证的 MiMo 载荷投影到现有安全静态授权格式。
/// The selected service and URL must match the issued key; the label identifies this attempt.
/// 所选服务与地址必须匹配签发的密钥，标签标识本次尝试。
fn credential_material(
    key: AuthorizedKey,
    service: MiMoService,
    service_base_url: &str,
    key_name: String,
) -> Result<CredentialSecretMaterial, String> {
    if key.url != service_base_url {
        return Err(String::from(
            "Xiaomi MiMo authorized a different product or region. Select the matching service entry and try again.",
        ));
    }
    if !key
        .sk
        .strip_prefix(service.key_prefix())
        .is_some_and(|suffix| {
            !suffix.is_empty() && suffix.bytes().all(|byte| byte.is_ascii_graphic())
        })
    {
        return Err(String::from(
            "Xiaomi MiMo returned a key for a different product or an invalid key.",
        ));
    }
    // material uses the upstream account identifier as its display handle because the response carries no user name.
    // 响应未携带用户名，material 使用上游账号标识作为账号显示标识。
    let material = CredentialSecretMaterial::BrowserCallbackAuthorization {
        secret: key.sk,
        projection: BrowserCallbackSecretProjection::ApiKey,
        provider_subject: key.uid.clone(),
        provider_username: key.uid,
        credential_label: key_name,
    };
    CredentialSecretEnvelope::new(material.clone())?;
    Ok(material)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Exercises the documented X25519 and GCM format through the registered localhost transaction.
    /// 通过已注册的本地主机事务验证文档所述 X25519 和 GCM 格式。
    #[tokio::test]
    async fn xiaomi_login_accepts_the_exact_encrypted_callback() {
        // runtime uses a synthetic browser with no network access to the platform.
        // runtime 使用不访问平台的合成浏览器。
        let runtime = OAuthAuthorizationRuntime::new(Client::new());
        // base_url pins the test to one regional Token Plan entry.
        // base_url 将测试固定到一个区域 Token Plan 入口。
        let base_url = "https://token-plan-ams.xiaomimimo.com/v1";
        // challenge exposes the public parameters used by the official page.
        // challenge 公开官方页面使用的公开参数。
        let challenge = runtime
            .start_xiaomi_mimo(String::from("test-binding"), base_url)
            .await
            .unwrap();
        // url and query carry the encoded public key and loopback redirect.
        // url 与 query 承载编码后的公钥和回环跳转。
        let url = Url::parse(&challenge.authorization_url).unwrap();
        let query: BTreeMap<_, _> = url.query_pairs().collect();
        // redirect resolves only to the local listener.
        // redirect 只解析到本地监听器。
        let redirect = Url::parse(query.get("redirect_uri").unwrap()).unwrap();
        // der starts with the exact SPKI prefix accepted by the official page.
        // der 以官方页面接受的精确 SPKI 前缀开头。
        let der = URL_SAFE_NO_PAD
            .decode(query.get("pk").unwrap().as_bytes())
            .unwrap();
        // peer is the Vulcan transaction's public key.
        // peer 是 Vulcan 事务的公钥。
        let peer = agreement::UnparsedPublicKey::new(
            &agreement::X25519,
            der.strip_prefix(X25519_SPKI_PREFIX).unwrap(),
        );
        // sender_private and sender_public simulate the browser's ephemeral exchange pair.
        // sender_private 与 sender_public 模拟浏览器的临时交换密钥对。
        let sender_private =
            agreement::EphemeralPrivateKey::generate(&agreement::X25519, &SystemRandom::new())
                .unwrap();
        let sender_public = sender_private.compute_public_key().unwrap();
        // key follows the official SHA-256 derivation before encryption.
        // key 在加密前遵循官方 SHA-256 派生方式。
        let key = agreement::agree_ephemeral(sender_private, &peer, |shared| {
            aead::UnboundKey::new(&aead::AES_256_GCM, &Sha256::digest(shared)).unwrap()
        })
        .unwrap();
        // nonce is a fixed synthetic value used once with the test's ephemeral key.
        // nonce 是只与测试临时密钥使用一次的固定合成值。
        let nonce = [42; aead::NONCE_LEN];
        // ciphertext begins as the exact official plaintext field shape.
        // ciphertext 的初值为精确的官方明文字段结构。
        let mut ciphertext = serde_json::to_vec(&serde_json::json!({
            "sk": "tp-synthetic", "uid": "synthetic-user", "url": base_url
        }))
        .unwrap();
        aead::LessSafeKey::new(key)
            .seal_in_place_append_tag(
                aead::Nonce::assume_unique_for_key(nonce),
                aead::Aad::empty(),
                &mut ciphertext,
            )
            .unwrap();
        // encoded concatenates the wire components in the official order.
        // encoded 按官方顺序串联线协议分量。
        let encoded =
            URL_SAFE_NO_PAD.encode([sender_public.as_ref(), &nonce, &ciphertext].concat());
        // port targets the reserved local listener without contacting the platform.
        // port 指向已保留的本地监听器，无需联系平台。
        let port = redirect.port().unwrap();
        // stream sends the same path and Host as the current platform web client.
        // stream 发送与当前平台网页客户端相同的路径与 Host。
        let mut stream = TcpStream::connect(("127.0.0.1", port)).await.unwrap();
        stream
            .write_all(
                format!("GET /auth?u={encoded} HTTP/1.1\r\nHost: localhost:{port}\r\n\r\n")
                    .as_bytes(),
            )
            .await
            .unwrap();
        // id is used to wait for the shared authorization runtime to publish success.
        // id 用于等待共享授权运行时发布成功。
        let id = &challenge.transaction.transaction_id;
        timeout(Duration::from_secs(3), async {
            while runtime.status(id).await.unwrap().phase
                == OAuthTransactionPhase::WaitingForCallback
            {
                tokio::task::yield_now().await;
            }
        })
        .await
        .unwrap();
        assert!(matches!(
            runtime.take_succeeded(id).await.unwrap(),
            CredentialSecretMaterial::BrowserCallbackAuthorization { secret, provider_subject, .. }
                if secret == "tp-synthetic" && provider_subject == "synthetic-user"
        ));
    }

    /// A key issued for a different regional host cannot be committed under the selected entry.
    /// 为其他区域主机签发的密钥不能提交到所选入口。
    #[test]
    fn xiaomi_login_rejects_cross_region_delivery() {
        assert!(
            credential_material(
                AuthorizedKey {
                    sk: String::from("tp-synthetic"),
                    uid: String::from("synthetic-user"),
                    url: String::from("https://token-plan-sgp.xiaomimimo.com/v1"),
                },
                MiMoService::PersonalTokenPlan,
                "https://token-plan-ams.xiaomimimo.com/v1",
                String::from("test-key"),
            )
            .is_err()
        );
    }
}
