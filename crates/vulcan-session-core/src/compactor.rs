use crate::context::{SessionCompactionCheckpoint, SessionContextDocument};
use crate::model::SessionNodeId;
use crate::policy::ExecutionRuntimePolicy;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::error::Error;
use std::fmt;

/// Shared context compaction request for any session node.
/// 任意会话节点共享的上下文压缩请求。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SessionContextCompactionRequest {
    /// Session node that owns the context.
    /// 拥有该上下文的会话节点。
    pub node_id: SessionNodeId,
    /// Runtime policy that must be respected during compaction.
    /// 压缩期间必须遵守的运行时策略。
    pub runtime_policy: ExecutionRuntimePolicy,
    /// Current context document before compaction.
    /// 压缩前的当前上下文文档。
    pub current_context: SessionContextDocument,
    /// Additional caller-owned compaction payload.
    /// 调用方拥有的额外压缩载荷。
    pub payload: Value,
}

/// Shared context compaction outcome for any session node.
/// 任意会话节点共享的上下文压缩结果。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SessionContextCompactionOutcome {
    /// Session node that owns the compacted context.
    /// 拥有压缩后上下文的会话节点。
    pub node_id: SessionNodeId,
    /// Updated context document after compaction.
    /// 压缩后的更新上下文文档。
    pub compacted_context: SessionContextDocument,
    /// Checkpoint generated by the compaction pass.
    /// 本次压缩生成的检查点。
    pub checkpoint: SessionCompactionCheckpoint,
}

/// Error returned by a shared context compactor.
/// 共享上下文压缩器返回的错误。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionContextCompactionError {
    /// Human-readable error message.
    /// 面向人的错误信息。
    pub message: String,
}

impl SessionContextCompactionError {
    /// Creates a context compaction error from a message.
    /// 使用消息创建上下文压缩错误。
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl fmt::Display for SessionContextCompactionError {
    /// Formats the error message.
    /// 格式化错误信息。
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl Error for SessionContextCompactionError {}

/// Shared compaction contract implemented by the runtime adapter.
/// 由运行时适配器实现的共享压缩契约。
pub trait SessionContextCompactor: Send + Sync {
    /// Compacts one session node context while respecting its runtime policy.
    /// 在遵守运行时策略的前提下压缩一个会话节点上下文。
    fn compact(
        &self,
        request: SessionContextCompactionRequest,
    ) -> Result<SessionContextCompactionOutcome, SessionContextCompactionError>;
}
