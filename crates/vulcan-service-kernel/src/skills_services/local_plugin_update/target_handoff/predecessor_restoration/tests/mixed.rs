/// One deadline bounds real native, Hook and formal-parent cleanup observations.
/// 单个截止时间限制真实原生、Hook 及正式父级清理观察。
const OBSERVE: std::time::Duration = std::time::Duration::from_secs(10);

/// Production qualifies the fixture's declared plugin ID and local server ID as plugin_id:server_id.
/// 生产将夹具声明的插件身份及本地服务器身份限定为 plugin_id:server_id。
const SERVER_ID: &str = "published-service:actual";

/// Nonblocking native publication records only effects emitted by actual Lua module execution.
/// 非阻塞原生发布仅记录实际 Lua 模块执行发出的副作用。
#[derive(Default)]
struct Events {
    /// Exact native events retain initialization, lifecycle and Hook retirement evidence in order.
    /// 精确原生事件依序保留初始化、生命周期及 Hook 退役证据。
    values: Mutex<Vec<VulcanPluginUiInvalidation>>,
}

impl VulcanPluginUiEventPublisher for Events {
    /// Append event from the actual host call; return synchronization failure without blocking its worker.
    /// 追加实际宿主调用的 event；返回同步失败，不阻塞其工作者。
    fn publish(&self, event: VulcanPluginUiInvalidation) -> Result<(), String> {
        self.values
            .lock()
            .map_err(|error| error.to_string())?
            .push(event);
        Ok(())
    }
}

impl Events {
    /// Return the complete ordered native effects; no input and no fabricated lifecycle observations.
    /// 返回完整有序原生副作用；无输入，不伪造生命周期观测。
    fn snapshot(&self) -> Vec<VulcanPluginUiInvalidation> {
        self.values.lock().expect("actual mixed Lua events").clone()
    }
}

/// Capture state's actual Full under the publication mutex; return its original Arc allocation.
/// 在发布互斥锁内捕获 state 的实际完整槽；返回其原 Arc 分配。
fn full(state: &SharedServiceBridgeState) -> Arc<ExtensionGeneration> {
    Arc::clone(
        &state
            .lock()
            .expect("actual mixed Full")
            .agent_runtime
            .as_ref()
            .expect("actual mixed bridge")
            .extension_generation,
    )
}

/// Dispatch state/full's captured real Hook partition; return its persistent module counter for this invocation.
/// 派发 state／full 捕获的真实 Hook 分区；返回本次调用的持久模块计数器。
/// run identifies only host dispatch correlation; the service's actual shared dispatcher supplies point authority.
/// run 仅标识宿主调度关联；服务实际共享调度器提供点位权威。
async fn hook_count(
    state: &SharedServiceBridgeState,
    full: &Arc<ExtensionGeneration>,
    run: &str,
) -> u64 {
    // Release the service mutex before borrowing the real conversation dispatcher and before awaiting Lua.
    // 借用真实会话调度器及等待 Lua 之前，释放服务互斥锁。
    let conversation = Arc::clone(
        &state
            .lock()
            .expect("actual mixed bridge")
            .agent_runtime
            .as_ref()
            .expect("actual bridge")
            .conversation_hook_runtime,
    );
    // Only handlers from the captured actual Full are projected into this asynchronous request.
    // 仅捕获实际完整槽的处理器投影至此异步请求。
    let dispatcher = ConversationHookGenerationGuard::new(
        conversation.lock().expect("actual conversation lock"),
        Some(
            full.plugin_conversation_hooks()
                .expect("actual mixed Full Hook partition"),
        ),
    )
    .expect("actual Full-scoped dispatcher")
    .dispatcher_mut()
    .clone();
    // Session identity satisfies the actual conversation point's host scope contract.
    // 会话身份满足实际会话点位的宿主作用域契约。
    let mut context = HookContext::new(run, "conversation.turn.precheck");
    context.scope = HookScope::Session;
    context.actor = HookActor::new("mixed-predecessor-test");
    context.session_id = Some(String::from("mixed-predecessor-session"));
    context.conversation_id = Some(String::from("mixed-predecessor-session"));
    // The returned payload is generated by actual Lua through the frozen production handler.
    // 返回载荷由实际 Lua 经冻结生产处理器生成。
    let report = dispatcher
        .dispatch(HookDispatchRequest::new(
            context,
            HookPayload::empty_object(),
        ))
        .await
        .expect("actual captured Lua Hook business");
    report.payload.value["count"]
        .as_u64()
        .expect("actual Lua module counter")
}

/// Invoke the real original_process binding captured by full; return the child PID that handled message.
/// 调用 full 捕获的真实 original_process 绑定；返回处理 message 的子进程 PID。
async fn invoke_pid(full: &Arc<ExtensionGeneration>, message: &str) -> u64 {
    // The remote declaration is qualified by the same actual server identifier used for source verification.
    // 远端声明由来源校验使用的相同实际服务器身份限定。
    let tool_id = format!("{SERVER_ID}/original_process");
    // Match immutable declaration identity rather than assuming an inventory position.
    // 匹配不可变声明身份，不假设清单位置。
    let binding = full
        .mcp_runtime()
        .available_tool_bindings_filtered(&McpRuntimeToolAllowlist::default())
        .into_iter()
        .find(|binding| binding.origin_tool_id() == tool_id)
        .expect("expected actual original_process declaration may have changed");
    // This response proves normal business reached the retained physical B.
    // 此响应证明普通业务到达保留物理 B。
    let result = binding
        .invoke(serde_json::json!({"message":message}))
        .await
        .expect("actual B business");
    assert_eq!(result["message"], message);
    result["pid"].as_u64().expect("actual B response PID")
}

/// Public same-request resume publishes the original Ready Hook and Node after real Full preparation fails.
/// 真实完整槽准备失败后，公开同请求恢复发布原就绪 Hook 及 Node。
/// No inputs or return; real module effects, Source identity, native IDs, Full/catalog Arcs and File contention prove reuse.
/// 无输入或返回值；真实模块副作用、来源身份、原生身份、完整槽／目录 Arc 及文件争用证明复用。
#[tokio::test]
async fn full_failure_reuses_same_actual_lua_hook_and_node_predecessor() {
    // This recorder observes actual native effects and never controls or simulates readiness.
    // 此记录器观察实际原生副作用，绝不控制或模拟就绪。
    let events = Arc::new(Events::default());
    // The variant is fully declared before the unchanged real configured immutable writer runs.
    // 变体在未变真实已配置不可变写入器运行之前完整声明。
    let configured = fixture_with_hook(events.clone());
    // Execute twice before update so original A's persistent Hook is proved rather than merely declared.
    // 更新之前执行两次，证明原 A 持久 Hook，不能仅有声明。
    let initial = full(&configured.state);
    assert_eq!(
        hook_count(&configured.state, &initial, "old-hook-first").await,
        1
    );
    assert_eq!(
        hook_count(&configured.state, &initial, "old-hook-second").await,
        2
    );
    assert_eq!(
        events
            .snapshot()
            .iter()
            .filter(|event| event.topic == "module-initialize")
            .count(),
        1,
        "the original persistent Hook must initialize one actual Lua module"
    );
    drop(initial);
    // Unchanged production preparation starts true Node A, drains old work and fails the actual bad-binary candidate.
    // 未变生产准备启动真实 Node A，排空旧工作，并让实际坏二进制候选失败。
    let fixture = failed_update_with_fixture(configured, false).await;
    // Retain only the actual manager and first issuer, without issuing another native registration.
    // 仅保留实际管理器及首次签发者，不签发另一原生注册。
    let (manager, authority) =
        crate::service_state_access::service_vulcan_plugin_native_mcp_host(&fixture.state)
            .expect("actual mixed manager and first issuer");
    // Capture real A identity before public compensation can initialize restored B.
    // 在公开补偿能够初始化恢复 B 之前，捕获真实 A 身份。
    let original_starts = starts(&fixture.marker);
    assert_eq!(original_starts.len(), 1);
    // Select recorded identity by its field, never by an evolving record index.
    // 按字段选择记录身份，绝不按会演进的记录下标选择。
    let original_pid = original_starts.first().expect("actual A start")["pid"]
        .as_u64()
        .expect("actual A PID");
    assert!(
        events
            .snapshot()
            .iter()
            .any(|event| event.topic == "disable")
    );
    assert!(
        events
            .snapshot()
            .iter()
            .any(|event| event.topic == "hook-shutdown" && event.revision == 2)
    );
    // Keep the exact actual prior Full to restore immediately after the injected revision failure.
    // 保留精确实际先前完整槽，以在注入修订失败后立即恢复。
    let previous = full(&fixture.state);
    // A standalone MAX fault generation retains the exact prior routing inputs; no business dispatch uses this temporary slot.
    // 独立 MAX 故障代次保留精确先前路由输入；任何业务调度都不使用此临时槽。
    let exhausted = Arc::new(ExtensionGeneration::new(
        u64::MAX,
        previous.plugin_catalog(),
        previous.mcp_runtime(),
        previous.prompt_skill_catalog(),
    ));
    fixture
        .state
        .lock()
        .expect("actual MAX injection")
        .agent_runtime
        .as_mut()
        .expect("actual bridge")
        .extension_generation = Arc::clone(&exhausted);
    // The genuine public abort reaches old Hook prewarm and native readiness before failing Full preparation.
    // 真实公开中止先到达旧 Hook 预热及原生就绪，再于完整槽准备失败。
    let failed = crate::skills_services::service_abort_local_plugin_update(
        Arc::clone(&fixture.state),
        String::from("published-service"),
        fixture.prepared.request_id().to_string(),
        true,
    )
    .await;
    // Undo the actual publication-slot fault before assertions can unwind with it installed.
    // 在断言可能展开之前撤销实际发布槽故障。
    let observed = full(&fixture.state);
    fixture
        .state
        .lock()
        .expect("restore actual previous Full")
        .agent_runtime
        .as_mut()
        .expect("actual bridge")
        .extension_generation = Arc::clone(&previous);
    assert!(Arc::ptr_eq(&observed, &exhausted));
    assert!(
        failed
            .expect_err("actual MAX Full preparation fails")
            .contains("Extension generation revision exhausted.")
    );
    // The complete Aborted original remains unchanged through subsequent same-request restoration.
    // 完整 Aborted 原请求跨随后同请求恢复保持不变。
    let request = fixture.prepared.request_id();
    // This is the actual durable body, not a reconstructed source or transfer permit.
    // 此为实际持久正文，不是重建来源或转交许可。
    let aborted = fixture
        .store
        .activation_transaction("published-service", request)
        .expect("actual Aborted read")
        .expect("actual Aborted original");
    assert_eq!(
        aborted.phase(),
        VulcanPluginActivationTransactionPhase::Aborted
    );
    assert_eq!(aborted.predecessor(), fixture.prepared.predecessor());
    assert_eq!(aborted.target(), fixture.prepared.target());
    // Pending still holds the original independent File despite actual old Hook and B already being ready.
    // 实际旧 Hook 及 B 已就绪时，Pending 仍持有原独立文件。
    let pending = fixture
        .store
        .predecessor_handoff_record("published-service", request)
        .expect("actual Pending read")
        .expect("actual Pending exists");
    assert_eq!(
        pending.phase(),
        VulcanPluginPredecessorHandoffPhase::Pending
    );
    assert_eq!(pending.original(), &fixture.prepared);
    // This competing handle never participates in production ownership; it only probes the existing physical lock.
    // 此竞争句柄绝不参与生产所有权；仅探测既有物理锁。
    let competing = handoff_file(&fixture);
    assert!(matches!(
        competing.try_lock(),
        Err(std::fs::TryLockError::WouldBlock)
    ));
    assert_eq!(
        manager.snapshot().plugins["published-service"].runtime_state,
        VulcanPluginRuntimeState::Enabling
    );
    // Borrow the actual registry slot only long enough to copy weak identity and pure native observations.
    // 仅足够复制弱身份及纯原生观测期间借用实际注册表槽。
    let registry = pending_owner::admitted_registry(&fixture.state).expect("actual mixed registry");
    // Lookup uses the allocator's canonical original UUID without creating a new owner.
    // 查询使用分配器规范原 UUID，不创建新所有者。
    let owner = registry
        .get("published-service", request)
        .expect("actual owner lookup")
        .expect("retained actual owner");
    // Copy weak Source identity and native IDs; the same actual owner remains alive to prove retirement is independent of executor drop.
    // 复制弱来源身份及原生身份；同实际所有者保持存活，证明退休独立于执行器销毁。
    let (source, control, profile, native_ids, private_binding) = {
        // This is the same production mutex holding the initialized Hook/source/native pair after the error.
        // 此为错误后持有已初始化 Hook／来源／原生配对的相同生产互斥锁。
        let resources = owner.resources.lock().await;
        // Only actual restoration allocated by the public abort may supply source and native.
        // 仅公开中止分配的实际恢复可提供来源及原生对象。
        let restoration = resources
            .target
            .as_ref()
            .expect("actual enabled owner")
            .restoration
            .as_ref()
            .expect("actual retained restoration");
        // Borrow the existing source allocation rather than manufacturing recovery authority.
        // 借用既有来源分配，不制造恢复权威。
        let source = restoration.source.as_ref().expect("actual retained Source");
        // Its native participant was already observed Ready by the production coordinator.
        // 其原生参与者已由生产协调器观察为就绪。
        let native = restoration.native.as_ref().expect("actual retained B");
        assert!(native.control().matches_source(source));
        // Preparing permits synchronous connected-input source verification while still withholding business transport acquisition.
        // Preparing 允许同步已连接输入来源校验，同时仍拒绝业务传输获取。
        native
            .verify_source(SERVER_ID, &native.profile())
            .expect("actual same-source private Ready inputs");
        // Derive the qualified remote tool identity from the sole actual server identity.
        // 从唯一实际服务器身份派生限定远端工具身份。
        let tool_id = format!("{SERVER_ID}/original_process");
        // This actual Preparing lease can expose discovered bindings but cannot admit their business invocation.
        // 此实际 Preparing 租约可暴露已发现绑定，但不能准入其业务调用。
        let binding = native
            .prepared_tool_bindings_filtered(&McpRuntimeToolAllowlist::default())
            .expect("actual private Ready tool discovery")
            .into_iter()
            .find(|binding| binding.origin_tool_id() == tool_id)
            .expect("expected real private original_process declaration may have changed");
        (
            Arc::downgrade(source),
            native.control(),
            native.profile(),
            native.actual_instance_ids(),
            binding,
        )
    };
    // The real binding rejects business at Preparing; this error is independent of source-ID observation.
    // 真实绑定在 Preparing 拒绝业务；此错误独立于来源身份观测。
    let blocked = private_binding
        .invoke(serde_json::json!({"message":"private B must remain closed"}))
        .await
        .expect_err("actual Preparing binding must reject valid business input");
    assert!(
        blocked.starts_with("mcp_server_disconnected:"),
        "expected actual business-gate rejection: {blocked}"
    );
    // Release this temporary actual lease before public resume so it contributes no transfer or cleanup ownership.
    // 公开恢复之前释放此临时实际租约，使其不贡献转交或清理所有权。
    drop(private_binding);
    assert_ne!(native_ids.0, native_ids.1);
    assert!(
        profile.same_source(
            &control
                .host_profile(&authority)
                .expect("actual first issuer profile")
        )
    );
    // The error's actual events include restored module/lifecycle work; retry must not append any of those effects.
    // 错误的实际事件包含恢复模块／生命周期工作；重试绝不能追加任何这些副作用。
    let before_resume = events.snapshot();
    assert!(before_resume.iter().any(|event| event.topic == "enable"));
    // The actual restored child differs from physically drained A and must remain the only B after retry.
    // 实际恢复子进程区别于已物理排空 A，且重试后必须仍为唯一 B。
    let actual_starts = starts(&fixture.marker);
    assert_eq!(actual_starts.len(), 2);
    // Identity selection is independent of marker ordering.
    // 身份选择独立于标记顺序。
    let restored_pid = actual_starts
        .iter()
        .map(|record| record["pid"].as_u64().expect("actual child PID"))
        .find(|pid| *pid != original_pid)
        .expect("actual B differs from A");
    crate::skills_services::service_resume_local_plugin_update(
        ServiceEventEmitter::new(Vec::new()),
        Arc::clone(&fixture.state),
        String::from("published-service"),
        request.to_string(),
    )
    .await
    .expect("actual public mixed same-request resume");
    assert_eq!(
        events.snapshot(),
        before_resume,
        "same-source retry must not initialize or replay lifecycle work"
    );
    assert_eq!(starts(&fixture.marker), actual_starts);
    // The final service Full owns the exact core catalog and exact captured Hook catalog allocation.
    // 最终服务完整槽拥有精确核心目录及精确捕获 Hook 目录分配。
    let committed = full(&fixture.state);
    assert!(!Arc::ptr_eq(&previous, &committed));
    assert!(Arc::ptr_eq(
        &committed.plugin_catalog().expect("final actual catalog"),
        &manager.snapshot()
    ));
    assert!(Arc::ptr_eq(
        &committed
            .plugin_conversation_hooks()
            .expect("final actual Hook partition")
            .catalog(),
        &manager.snapshot()
    ));
    assert_eq!(
        manager.snapshot().plugins["published-service"].runtime_state,
        VulcanPluginRuntimeState::Enabled
    );
    {
        // Borrow the same original resources after transfer; no new getter or physical observation owner is needed.
        // 转交后借用同原资源；无须新访问器或物理观测所有者。
        let resources = owner.resources.lock().await;
        // The retired service slot still exposes its genuine completed restoration while this executor reference lives.
        // 此执行器引用存活时，已退休服务槽仍暴露其真实已完成恢复。
        let restoration = resources
            .target
            .as_ref()
            .expect("same completed enabled owner")
            .restoration
            .as_ref()
            .expect("same completed actual restoration");
        // Weak allocation equality observes the retained original without claiming Native must own its Source after transfer.
        // 弱分配相等观察保留原来源，不声称转交之后原生对象必须拥有其来源。
        let transferred_source = restoration
            .source
            .as_ref()
            .expect("same retained completed Source");
        // Actual native IDs originate from this very participant before and after the successful public retry.
        // 成功公开重试前后，实际原生身份源自此同一参与者。
        let native = restoration
            .native
            .as_ref()
            .expect("same completed actual B");
        assert!(restoration.transferred);
        assert!(std::sync::Weak::ptr_eq(
            &source,
            &Arc::downgrade(transferred_source)
        ));
        assert!(control.matches_source(transferred_source));
        assert!(native.control().matches_source(transferred_source));
        assert_eq!(native.actual_instance_ids(), native_ids);
        assert!(profile.same_source(&native.profile()));
        native
            .verify_source(SERVER_ID, &profile)
            .expect("transferred original connected inputs are open");
    }
    assert_eq!(
        invoke_pid(&committed, "same mixed B after resume").await,
        restored_pid
    );
    assert_eq!(
        hook_count(&fixture.state, &committed, "restored-hook-first").await,
        1
    );
    assert_eq!(
        hook_count(&fixture.state, &committed, "restored-hook-second").await,
        2
    );
    assert_eq!(events.snapshot(), before_resume);
    assert_eq!(
        fixture
            .store
            .activation_transaction("published-service", request)
            .expect("unchanged complete original")
            .as_ref(),
        Some(&aborted)
    );
    assert_eq!(
        fixture
            .store
            .predecessor_handoff_record("published-service", request)
            .expect("actual transfer read")
            .expect("actual transfer exists")
            .phase(),
        VulcanPluginPredecessorHandoffPhase::Transferred
    );
    competing
        .try_lock()
        .expect("actual independent File released after joint transfer");
    competing.unlock().expect("release independent probe");
    assert!(
        registry
            .get("published-service", request)
            .expect("actual retired owner lookup")
            .is_none()
    );
    // Both registry retirement and File release already succeeded while the actual executor's owner was still alive.
    // 实际执行器所有者仍存活时，注册表退休及文件释放均已成功。
    drop(owner);
    crate::skills_services::service_abort_local_plugin_update(
        Arc::clone(&fixture.state),
        String::from("published-service"),
        request.to_string(),
        true,
    )
    .await
    .expect("historical same-request abort");
    assert!(Arc::ptr_eq(&committed, &full(&fixture.state)));
    assert_eq!(events.snapshot(), before_resume);
    assert_eq!(starts(&fixture.marker), actual_starts);
    // Retire the genuine published B and its persistent Hook before disposing their actual formal parent.
    // 销毁实际正式父级之前，退役真实已发布 B 及其持久 Hook。
    let access = committed.mcp_runtime();
    access
        .begin_plugin_mcp_drain("published-service")
        .expect("actual mixed native shutdown");
    access
        .wait_plugin_mcp_drain("published-service", OBSERVE)
        .await
        .expect("actual mixed native retirement");
    manager
        .begin_draining("published-service")
        .expect("actual mixed Hook shutdown admission");
    // A bounded actual drain reports the same persistent Hook instance's physical shutdown.
    // 有界实际排空报告相同持久 Hook 实例的物理关闭。
    let drained = tokio::time::timeout(OBSERVE, manager.drain_plugin_sessions("published-service"))
        .await
        .expect("bounded actual Hook drain")
        .expect("actual Hook retirement");
    assert!(
        drained.failures.is_empty(),
        "actual Hook cleanup failed: {:?}",
        drained.failures
    );
    assert_eq!(drained.closed_hook_runtimes, 1);
    assert_eq!(
        events
            .snapshot()
            .iter()
            .filter(|event| event.topic == "hook-shutdown" && event.revision == 2)
            .count(),
        2
    );
    manager
        .request_formal_runtime_close()
        .expect("actual mixed parent close request");
    tokio::time::timeout(OBSERVE, async {
        while !manager
            .poll_formal_runtime_closed()
            .expect("actual mixed parent close observation")
        {
            tokio::task::yield_now().await;
        }
    })
    .await
    .expect("bounded actual mixed parent close");
}
