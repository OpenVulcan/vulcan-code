//! Actual Lua Hook and Node predecessor survive one Full preparation failure without replay.
//! 实际 Lua Hook 及 Node 前驱跨单次完整槽准备失败存续，不重播。

use super::*;
use crate::skills_services::vulcan_plugin_lifecycle::generation_tests::published::fixture_with_hook;
