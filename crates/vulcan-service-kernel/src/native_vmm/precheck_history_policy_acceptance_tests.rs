//! Real mixed-state history windowing after formal global and caller policy saves.
//! 正式全局及调用方策略保存后的真实混合状态历史窗口。

use super::*;

#[path = "precheck_history_parity_acceptance_tests.rs"]
mod external_parity;

/// Identifies the exact session shared by both bound callers in this acceptance.
/// 标识本验收两个已绑定调用方共享的准确会话。
const SESSION: &str = "precheck-history-session";
/// Keeps the canonical final answer distinct from extracted user details.
/// 使规范最终回答与提炼的用户详情保持不同。
const ASSISTANT: &str = "已记录数据库部署要求，后续按这条规则检查配置。";

/// Returns one explicit natural-language source body for the supplied ordinal.
/// 为传入序号返回一份明确自然语言来源正文。
/// The marker distinguishes real persisted turns without relying on generated timestamps or IDs.
/// 标记用于区分真实持久回合，不依赖生成时间戳或 ID。
fn body(index: usize) -> String {
    // The four primary source inputs are shared with the external production oracle before cleaning.
    // 四条主来源输入在清洗前即与外置生产对照共用。
    if index < 4 {
        return external_parity::fixture().sources[index].clone();
    }
    format!(
        "项目数据库采用 PostgreSQL，部署前必须核对备份与连接配置，这是历史验收规则第 {index} 条。"
    )
}

/// Admits one real turn and returns its exact durable ready job.
/// 准入一个真实回合，并返回其准确耐久就绪作业。
/// Takes the production client/data plane, bound caller, project, session and source ordinal; never forges Core state.
/// 接收生产客户端／数据面、已绑定调用方、项目、会话及来源序号；绝不伪造 Core 状态。
async fn intake(
    client: &NativeVmmClient,
    data_plane: &VmmDataPlaneHandle,
    caller: &str,
    project_id: u64,
    session: &str,
    index: usize,
) -> NativeVmmPendingAnalysisJob {
    // Each accepted source has its own stable operation, independently of session and project names.
    // 每份已接纳来源具有自己的稳定操作身份，独立于会话及项目名称。
    let operation = format!("precheck-history-source-{index}");
    client
        .post_action(PostActionRequest {
            host_project_id: caller.to_owned(),
            project_id,
            user_id: 1,
            session_id: session.to_owned(),
            operation_id: operation.clone(),
            user_content: body(index),
            assistant_content: ASSISTANT.to_owned(),
            ..Default::default()
        })
        .await
        .expect("history source intake");
    // A successful response is insufficient: require the actual persisted queue row and turn identity.
    // 仅成功响应并不足够：要求实际持久队列记录及回合身份。
    let job = data_plane
        .load_pending_analysis_job(&operation)
        .await
        .expect("history ready job read")
        .expect("history ready job");
    assert_eq!(job.state, VMM_PENDING_ANALYSIS_READY);
    assert!(job.turn_id.is_some());
    job
}

/// Executes a real PreCheck and returns the sole observed L1 history array.
/// 执行真实预检，并返回唯一观察到的 L1 历史数组。
/// Takes the actual client/port and caller ownership; verifies unchanged current input and real empty retrieval.
/// 接收实际客户端／端口及调用方归属；验证当前输入保持及真实空检索。
async fn check_history(
    client: &NativeVmmClient,
    port: &CapturingAnalysisPort,
    project_id: u64,
    caller: &str,
) -> Vec<serde_json::Value> {
    // Own the starting offset so captures from earlier extraction cannot satisfy this precheck.
    // 独立持有起始偏移，使之前提炼的捕获不能满足此次预检。
    let before = port.requests.lock().expect("history capture start").len();
    // Even the empty physical project follows the real query-embedding path after affirmative intent.
    // 即使物理项目为空，肯定意图之后仍遵循真实查询向量路径。
    let embedding_before = port
        .embedding_requests
        .lock()
        .expect("history embedding start")
        .len();
    // The current user text is independent of historical limits, including a one-token history budget.
    // 当前用户文本独立于历史限制，包括仅一个令牌的历史预算。
    let result = client
        .pre_check(PreCheckRequest {
            host_project_id: caller.to_owned(),
            project_id,
            user_id: 1,
            session_id: SESSION.to_owned(),
            user_content: USER_PROMPT.to_owned(),
            operation_id: uuid::Uuid::new_v4().to_string(),
            recall_mode: PreCheckRecallMode::PreCheckRecallModeFull,
        })
        .await
        .expect("real history precheck");
    assert!(!result.degraded);
    assert!(!result.should_inject);
    assert!(result.context_items.is_empty());
    // No memory candidates were generated by extraction, so production must omit L2 review.
    // 提炼未生成记忆候选，因此生产必须省略 L2 审核。
    let requests = port.requests.lock().expect("history captures")[before..].to_vec();
    assert_eq!(requests.len(), 1);
    assert_eq!(requests[0].purpose_id, "precheck_l1");
    // Inspect the actual serialized business input rather than re-running the selection helper in the assertion.
    // 检查实际序列化业务输入，而不是在断言中重新运行选择辅助方法。
    let input = analysis_input(&requests[0]);
    assert_eq!(input["current_user_input"], USER_PROMPT);
    assert_eq!(input["max_search_queries"], 2);
    assert_eq!(
        port.embedding_requests
            .lock()
            .expect("history query embedding count")
            .len(),
        embedding_before + 1
    );
    input["recent_turns"]
        .as_array()
        .expect("actual L1 history")
        .clone()
}

/// Verifies both history controls on real completed/pending data, including exact-budget and frozen-call boundaries.
/// 在真实已完成／待处理数据上验证两个历史控制项，包括准确预算及冻结调用边界。
/// Takes isolated storage and its declared host capability; only model output and query vectors are deterministic fixtures.
/// 接收隔离存储及其声明宿主能力；仅模型输出及查询向量使用确定性夹具。
pub(in crate::native_vmm) async fn verify(
    data_plane: VmmDataPlaneHandle,
    capability: InferenceCapabilitySnapshot,
) {
    // Reuse the explicit affirmative intent fixture and its existing bounded admission pause.
    // 复用明确肯定意图夹具及其现有有界准入暂停。
    let port = Arc::new(CapturingAnalysisPort {
        inner: MockHostAiPort::new(),
        requests: StdMutex::new(Vec::new()),
        reject_next_turn: AtomicBool::new(false),
        fixture: AnalysisFixture::PrecheckPolicy(StdMutex::new(None)),
        embedding_requests: StdMutex::new(Vec::new()),
        profile_instruction_pause: StdMutex::new(None),
        postaction_pause: StdMutex::new(None),
    });
    port.inner
        .set_capability_snapshot(capability)
        .expect("history capability");
    // All canonical turns and jobs are owned by the actual native runtime over private disk.
    // 全部规范回合及作业由私有磁盘上的实际原生运行时持有。
    let runtime = Arc::new(
        NativeVmmCoreRuntime::bootstrap(port.clone(), data_plane.clone())
            .await
            .expect("history runtime"),
    );
    // Disable only unrelated semantic-noise inference; deterministic source admission stays production code.
    // 仅关闭无关语义噪声推理；确定性来源准入仍使用生产代码。
    let mut settings = runtime
        .resource_catalog()
        .await
        .expect("history resources")
        .settings;
    settings.noise_semantic_enabled = false;
    runtime
        .update_resource_settings(settings)
        .await
        .expect("history noise fixture");
    // A and B intentionally share one physical project so the caller override is the only policy discriminator.
    // A 与 B 有意共享一个物理项目，使调用方覆盖成为唯一策略判别依据。
    let project = data_plane
        .create_project("History policy", "history-policy")
        .await
        .expect("history project");
    for caller in ["precheck-host-a", "precheck-host-b"] {
        data_plane
            .bind_vulcan_project(caller, project.id)
            .await
            .expect("history binding");
    }
    // An independently bound project carries the same session name and must never enter the primary history window.
    // 独立绑定项目携带相同会话名，绝不能进入主历史窗口。
    let other = data_plane
        .create_project("History other", "history-other")
        .await
        .expect("other history project");
    data_plane
        .bind_vulcan_project("precheck-host-other", other.id)
        .await
        .expect("other history binding");
    // Share the same operation gate between public saves and client admission.
    // 在公开保存及客户端准入之间共享同一个操作锁。
    let gate = Arc::new(RwLock::new(()));
    // This service owns the exact runtime consumed by all later client commands.
    // 此服务持有随后全部客户端命令消费的准确运行时。
    let service = policy_service::service(runtime.clone(), data_plane.clone(), gate.clone());
    // The client performs real intake, background drains and precheck; no turn is inserted by the test.
    // 客户端执行真实入库、后台排空及预检；测试不直接插入回合。
    let client = NativeVmmClient::new(
        runtime.clone(),
        data_plane.clone(),
        gate.clone(),
        Arc::new(AtomicBool::new(true)),
        Arc::new(Notify::new()),
    );
    // Retain exact accepted jobs so final comparisons cover their complete scheduling and payload state.
    // 保留准确已接纳作业，使最终比较覆盖其完整调度及参数状态。
    let mut jobs = Vec::new();
    for index in 0..4 {
        // The first two turns are actually analyzed; the later two remain untouched in the durable ready queue.
        // 前两个回合实际完成分析；后两个回合保持在耐久就绪队列中不被处理。
        let job = intake(
            &client,
            &data_plane,
            "precheck-host-b",
            project.id,
            SESSION,
            index,
        )
        .await;
        if index < 2 {
            assert!(
                client
                    .drain_due_pending_analysis_jobs()
                    .await
                    .expect("history completed drain")
            );
            // Observe the real completion receipt instead of changing status in a snapshot.
            // 观察真实完成回执，而不是在快照中修改状态。
            let completed = data_plane
                .load_pending_analysis_job(&job.operation_id)
                .await
                .expect("history completion read")
                .expect("history completion");
            assert_eq!(
                completed.state, VMM_PENDING_ANALYSIS_COMPLETED,
                "{:?}",
                completed.last_error
            );
            assert_eq!(completed.attempt_count, 0);
            jobs.push(completed);
        } else {
            jobs.push(job);
        }
    }
    jobs.push(
        intake(
            &client,
            &data_plane,
            "precheck-host-b",
            project.id,
            "history-other-session",
            4,
        )
        .await,
    );
    jobs.push(
        intake(
            &client,
            &data_plane,
            "precheck-host-other",
            other.id,
            SESSION,
            5,
        )
        .await,
    );
    // Persisted mixed states are the acceptance precondition, not an assumption derived from the L1 response.
    // 持久混合状态是验收前置条件，不是从 L1 响应推导的假定。
    let original = runtime
        .storage_snapshot()
        .expect("history original snapshot");
    assert_eq!(original.dataset.turns.len(), 6);
    assert!(original.dataset.memories.is_empty());
    for (index, job) in jobs.iter().enumerate() {
        // Resolve every source by its actual admitted turn ID, including the two isolation records.
        // 按实际准入回合 ID 解析每份来源，包括两个隔离记录。
        let turn = original
            .dataset
            .turns
            .iter()
            .find(|turn| Some(turn.id.as_str()) == job.turn_id.as_deref())
            .expect("history canonical turn");
        assert_eq!(turn.timeline[0].content, body(index));
        if index < 2 {
            assert_eq!(turn.status, TurnStatus::Completed);
            assert_eq!(turn.analysis_details.as_deref(), Some(body(index).as_str()));
        } else {
            assert_eq!(job.state, VMM_PENDING_ANALYSIS_READY);
            assert_ne!(turn.status, TurnStatus::Completed);
            assert!(turn.analysis_details.is_none());
        }
    }
    // Start with a complete four-turn window under a deliberately non-binding historical token budget.
    // 从完整四回合窗口开始，历史令牌预算有意设置为不构成限制。
    let mut global = runtime
        .runtime_policy()
        .await
        .expect("history default policy")
        .recall;
    global.precheck_history_turn_limit = 4;
    global.precheck_max_input_tokens = 131_072;
    global.max_search_queries = 2;
    save_global(&service, &global).await;
    // Independently verify every full-window identity, content type and original business body before using this baseline.
    // 使用此基线前，独立验证完整窗口的每项身份、内容类型及原始业务正文。
    let full = check_history(&client, &port, project.id, "precheck-host-b").await;
    assert_eq!(full.len(), 4);
    for (index, observed) in full.iter().enumerate() {
        assert_eq!(
            observed["turn_id"],
            parse_core_numeric_id(
                jobs[index].turn_id.as_ref().expect("history turn ID"),
                "vmm-turn-"
            )
            .expect("numeric history turn")
        );
        if index < 2 {
            assert_eq!(observed["content_type"], "DETAILS");
            assert_eq!(observed["content"], body(index));
        } else {
            assert_eq!(observed["content_type"], "RAW_TURN");
            // Parse the observed compact JSON to compare its full business shape without assuming object-key order.
            // 解析观察到的紧凑 JSON，比对完整业务形态，不假定对象键顺序。
            let raw: serde_json::Value =
                serde_json::from_str(observed["content"].as_str().expect("raw history string"))
                    .expect("raw history JSON");
            assert_eq!(
                raw,
                serde_json::json!({"user": body(index), "timeline": [], "assistant": ASSISTANT})
            );
        }
    }
    // Compare escaped raw history and exact source-generated budgets through the actual host before policy isolation probes.
    // 在策略隔离探测前，经实际宿主比较转义后的原始历史与来源生成的准确预算。
    let external_calls =
        external_parity::verify(&client, &port, &service, project.id, &global, &full).await;
    // Explicit A history survives later global changes while B continuously inherits the newest saved group.
    // A 的明确历史设置在后续全局变化中保持，B 则持续继承最新保存组。
    let mut a = global.clone();
    a.precheck_history_turn_limit = 1;
    save_a(&service, Some(a.clone()), &a).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full[3..]
    );
    global.precheck_history_turn_limit = 2;
    save_global(&service, &global).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-b").await,
        full[2..]
    );
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full[3..]
    );
    save_a(&service, None, &global).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full[2..]
    );
    global.precheck_history_turn_limit = 4;
    global.precheck_max_input_tokens = 1;
    save_global(&service, &global).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-b").await,
        full[3..]
    );
    // Hold the same four-turn limit for both callers and vary only A's token budget to prove independent consumption.
    // 两个调用方保持同一四回合上限，仅改变 A 的令牌预算，以证明独立消费。
    a = global.clone();
    a.precheck_max_input_tokens = 131_072;
    save_a(&service, Some(a.clone()), &a).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full
    );
    // Sum the independently verified model-visible content using the declared shared estimator, not the selection helper.
    // 使用声明的共享估算器累加独立验证的模型可见正文，不调用选择辅助方法。
    let budgets = full
        .iter()
        .map(|turn| estimate_text_tokens(turn["content"].as_str().expect("history budget content")))
        .collect::<Vec<_>>();
    assert!(budgets.iter().all(|budget| *budget > 1));
    for start in [2, 1] {
        // Exact inclusion of two RAW turns, then DETAILS plus two RAW turns, must change at a single-token boundary.
        // 两个原始回合、随后详情加两个原始回合的准确接纳，必须在单个令牌边界发生变化。
        let exact: u32 = budgets[start..].iter().sum();
        global.precheck_max_input_tokens = exact;
        save_global(&service, &global).await;
        assert_eq!(
            check_history(&client, &port, project.id, "precheck-host-b").await,
            full[start..]
        );
        global.precheck_max_input_tokens = exact - 1;
        save_global(&service, &global).await;
        assert_eq!(
            check_history(&client, &port, project.id, "precheck-host-b").await,
            full[start + 1..]
        );
    }
    // A's large explicit budget must survive every intervening inherited-budget change.
    // A 的明确大预算必须在每次中间继承预算变化后保持。
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full
    );
    save_a(&service, None, &global).await;
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-a").await,
        full[2..]
    );
    global.precheck_max_input_tokens = 131_072;
    save_global(&service, &global).await;
    // Pause after the actual old four-turn history has been admitted into the L1 effect.
    // 在实际旧四回合历史准入 L1 效应之后暂停。
    let (entered, observed) = tokio::sync::oneshot::channel();
    // Formal persistence must finish before allowing the captured old command to resume.
    // 必须完成正式持久化后，才允许已捕获旧命令恢复。
    let (resume, resumed) = tokio::sync::oneshot::channel();
    // This slot belongs to the exact affirmative precheck fixture used by this client.
    // 此暂停槽属于本客户端所用的准确肯定预检夹具。
    let AnalysisFixture::PrecheckPolicy(slot) = &port.fixture else {
        panic!("history fixture mode")
    };
    *slot.lock().expect("history pause arm") = Some(IntentPause {
        entered,
        resume: resumed,
    });
    // The next-command settings differ in both window size and historical token budget.
    // 下一命令设置在窗口大小和历史令牌预算两方面均不同。
    let mut next = global.clone();
    next.precheck_history_turn_limit = 2;
    next.precheck_max_input_tokens = 1;
    // A real service save interleaves with the admitted model request, without synthetic timestamps or sleeps.
    // 真实服务保存与已准入模型请求交错，不使用合成时间戳或休眠。
    let (frozen, ()) = tokio::join!(
        check_history(&client, &port, project.id, "precheck-host-b"),
        async {
            tokio::time::timeout(Duration::from_secs(10), observed)
                .await
                .expect("history intent timeout")
                .expect("history intent reached");
            save_global(&service, &next).await;
            resume.send(()).expect("history intent resume");
        }
    );
    assert_eq!(frozen, full);
    assert_eq!(
        check_history(&client, &port, project.id, "precheck-host-b").await,
        full[3..]
    );
    // Neither historical trimming nor settings saves may silently analyze, rewrite or remove any source turn.
    // 历史裁剪及设置保存均不得静默分析、重写或移除任何来源回合。
    let persisted: vulcan_memorymesh_core::StorageSnapshot = serde_json::from_str(
        &data_plane
            .load_core_snapshot_json()
            .await
            .expect("history persisted read")
            .expect("history persisted bytes"),
    )
    .expect("history persisted snapshot");
    assert_eq!(persisted.dataset.turns, original.dataset.turns);
    assert!(persisted.dataset.memories.is_empty());
    for job in jobs {
        assert_eq!(
            data_plane
                .load_pending_analysis_job(&job.operation_id)
                .await
                .expect("history unchanged queue read")
                .expect("history unchanged queue"),
            job
        );
    }
    // Only two explicitly drained turns, fifteen original prechecks and source-oracle probes may invoke inference.
    // 仅两个明确排空回合、十五次原预检及来源对照探测可以调用推理。
    assert_eq!(
        port.requests
            .lock()
            .expect("history final model calls")
            .len(),
        17 + external_calls
    );
    assert_eq!(
        port.embedding_requests
            .lock()
            .expect("history final query calls")
            .len(),
        15 + external_calls
    );
    drop(client);
    drop(service);
    drop(runtime);
    // Reopen from the same real disk to prove the final saved limits and unchanged canonical turns survive reconstruction.
    // 从同一真实磁盘重开，证明最终保存限制及未变化规范回合在重建后保持。
    let reopened = NativeVmmCoreRuntime::bootstrap(port, data_plane)
        .await
        .expect("history reopen");
    assert_eq!(
        reopened
            .runtime_policy()
            .await
            .expect("history reopened policy")
            .recall,
        next
    );
    assert_eq!(
        reopened
            .storage_snapshot()
            .expect("history reopened turns")
            .dataset
            .turns,
        original.dataset.turns
    );
}
