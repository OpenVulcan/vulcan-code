//! Runtime layout manifest shared by the Core, the tray, and the desktop client.
//! Core、托盘与桌面客户端共用的运行时布局清单。
//!
//! One manifest names every release entry point, so no component guesses file names or walks a
//! directory looking for a plausible executable. All paths inside the manifest are relative to
//! the manifest directory and must resolve to a location inside that release root.
//! 一份清单声明全部发行入口，因此没有组件会去猜测文件名或遍历目录寻找“看起来像”的可执行文件。
//! 清单内的所有路径都相对清单所在目录，且必须解析到该发行根之内。

use std::path::{Component, Path, PathBuf};

/// Stable schema version of the runtime layout manifest.
/// 运行时布局清单的稳定架构版本。
pub const RUNTIME_LAYOUT_SCHEMA_VERSION: u32 = 3;

/// Default manifest file name generated by the build tooling.
/// 构建工具生成的默认清单文件名。
pub const RUNTIME_LAYOUT_FILENAME: &str = "runtime-layout.json";

/// Explicit override that names one exact manifest path.
/// 指定一份精确清单路径的显式覆盖入口。
pub const RUNTIME_LAYOUT_ENV: &str = "VULCAN_RUNTIME_LAYOUT";

/// One validated runtime layout manifest.
/// 一份已校验的运行时布局清单。
#[derive(Debug, Clone, serde::Deserialize, serde::Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RuntimeLayoutManifest {
    /// Manifest schema version; must equal [`RUNTIME_LAYOUT_SCHEMA_VERSION`].
    /// 清单架构版本；必须等于 [`RUNTIME_LAYOUT_SCHEMA_VERSION`]。
    pub schema_version: u32,
    /// Build profile that produced this layout: `debug` or `release`.
    /// 生成本布局的构建配置：`debug` 或 `release`。
    pub profile: String,
    /// Service executable path relative to the manifest directory.
    /// 相对清单目录的服务可执行文件路径。
    pub service_executable: String,
    /// Desktop client executable path relative to the manifest directory.
    /// 相对清单目录的桌面客户端可执行文件路径。
    pub desktop_executable: String,
    /// Desktop client entry script path relative to the manifest directory.
    /// 相对清单目录的桌面客户端入口脚本路径。
    pub desktop_entry: String,
    /// Terminal client executable path relative to the manifest directory.
    /// 相对清单目录的终端客户端可执行文件路径。
    pub tui_executable: String,
    /// Core browser host entry script path relative to the manifest directory.
    /// 相对清单目录的 Core 浏览器宿主入口脚本路径。
    pub browser_host_entry: String,
    /// Managed Node executable dedicated to the Core browser, relative to the distribution.
    /// Core 浏览器使用的受管 Node 程序，相对于发行根目录。
    pub browser_host_executable: String,
    /// Optional standalone Chromium executable supplied by the browser runtime package.
    /// 由可选浏览器运行时包提供的独立 Chromium 可执行文件。
    #[serde(default)]
    pub chromium_executable: Option<String>,
    /// Built WebUI root directory relative to the manifest directory.
    /// 相对清单目录的已构建 WebUI 根目录。
    pub webui_root: String,
    /// Runtime version string shared by all packaged components.
    /// 所有打包组件共享的运行时版本文本。
    pub runtime_version: String,
    /// Target platform identifier, for example `win32`.
    /// 目标平台标识，例如 `win32`。
    pub platform: String,
    /// Target architecture identifier, for example `x64`.
    /// 目标架构标识，例如 `x64`。
    pub architecture: String,
    /// Capability names this layout actually provides.
    /// 本布局实际提供的能力名称。
    #[serde(default)]
    pub capabilities: Vec<String>,
}

/// Returns the explicit manifest path from the environment when one was set.
/// 环境变量设置了显式清单路径时返回该路径。
///
/// # Returns
/// 返回值
/// `Ok(Some(path))` for a usable explicit path, `Ok(None)` when unset, or a diagnostic when the
/// explicit value is present but unusable.
/// 可用显式路径返回 `Ok(Some(path))`，未设置返回 `Ok(None)`，设置但不可用时返回诊断。
pub fn explicit_runtime_layout_path() -> Result<Option<PathBuf>, String> {
    let value = std::env::var(RUNTIME_LAYOUT_ENV).ok();
    explicit_runtime_layout_path_from(value.as_deref())
}

/// Validates one explicit override value without reading the process environment.
/// 在不读取进程环境的情况下校验一个显式覆盖值。
///
/// # Parameters
/// 参数
/// `value` is the raw override value, or `None` when the override is unset.
/// `value` 是原始覆盖值；未设置时为 `None`。
///
/// # Returns
/// 返回值
/// `Ok(Some(path))` for a usable absolute path, `Ok(None)` when unset, or a diagnostic.
/// 可用绝对路径返回 `Ok(Some(path))`，未设置返回 `Ok(None)`，否则返回诊断。
pub fn explicit_runtime_layout_path_from(value: Option<&str>) -> Result<Option<PathBuf>, String> {
    let Some(value) = value else {
        return Ok(None);
    };
    if value.trim().is_empty() {
        return Err(format!("{RUNTIME_LAYOUT_ENV} must not be empty when set"));
    }
    let path = PathBuf::from(value);
    if !path.is_absolute() {
        return Err(format!("{RUNTIME_LAYOUT_ENV} must be an absolute path"));
    }
    Ok(Some(path))
}

/// Resolves one manifest entry against the manifest directory without escaping the release root.
/// 在不逃逸发行根的前提下，将单个清单条目解析到清单目录之下。
///
/// # Parameters
/// 参数
/// `root` is the manifest directory, and `entry` is the manifest-provided relative path.
/// `root` 是清单目录，`entry` 是清单提供的相对路径。
///
/// # Returns
/// 返回值
/// The joined absolute path, or a diagnostic when the entry is absolute or escapes the root.
/// 返回拼接后的绝对路径；条目为绝对路径或逃逸根目录时返回诊断。
pub fn resolve_layout_entry(root: &Path, entry: &str) -> Result<PathBuf, String> {
    if entry.trim().is_empty() {
        return Err(String::from("runtime layout entry must not be empty"));
    }
    let candidate = Path::new(entry);
    if candidate.is_absolute() {
        return Err(format!(
            "runtime layout entry `{entry}` must be relative to the layout root"
        ));
    }
    // normalization walks components so a `..` segment can never escape the release root.
    // normalization 逐组件遍历，使 `..` 段永远无法逃逸发行根。
    let mut normalized = PathBuf::new();
    for component in candidate.components() {
        match component {
            Component::Normal(segment) => normalized.push(segment),
            Component::CurDir => {}
            Component::ParentDir | Component::RootDir | Component::Prefix(_) => {
                return Err(format!(
                    "runtime layout entry `{entry}` must not escape the layout root"
                ));
            }
        }
    }
    if normalized.as_os_str().is_empty() {
        return Err(format!("runtime layout entry `{entry}` must name a file"));
    }
    Ok(root.join(normalized))
}

/// Validates one parsed manifest against the schema contract.
/// 按架构契约校验一份已解析的清单。
fn validate_manifest(manifest: &RuntimeLayoutManifest) -> Result<(), String> {
    if manifest.schema_version != RUNTIME_LAYOUT_SCHEMA_VERSION {
        return Err(format!(
            "runtime layout schema version {} is not supported; expected {}",
            manifest.schema_version, RUNTIME_LAYOUT_SCHEMA_VERSION
        ));
    }
    if manifest.profile != "debug" && manifest.profile != "release" {
        return Err(format!(
            "runtime layout profile `{}` must be `debug` or `release`",
            manifest.profile
        ));
    }
    if manifest.runtime_version.trim().is_empty() {
        return Err(String::from(
            "runtime layout runtimeVersion must not be empty",
        ));
    }
    Ok(())
}

/// Reads and validates one manifest from an explicit path.
/// 从显式路径读取并校验一份清单。
pub fn read_runtime_layout_manifest_from(path: &Path) -> Result<RuntimeLayoutManifest, String> {
    let body = std::fs::read_to_string(path).map_err(|error| {
        format!(
            "failed to read runtime layout manifest {}: {error}",
            path.display()
        )
    })?;
    let manifest: RuntimeLayoutManifest = serde_json::from_str(&body).map_err(|error| {
        format!(
            "invalid runtime layout manifest {}: {error}",
            path.display()
        )
    })?;
    validate_manifest(&manifest)?;
    Ok(manifest)
}

/// Candidate manifest paths in explicit priority order.
/// 按明确优先级排列的候选清单路径。
///
/// # Returns
/// 返回值
/// Returns at most one explicit path, then the executable-adjacent path, then the debug
/// repository path. No directory is ever scanned.
/// 最多返回一个显式路径，其次是可执行文件同目录路径，最后是调试构建的仓库内路径；不扫描任何目录。
fn runtime_layout_candidates() -> Result<Vec<PathBuf>, String> {
    let mut candidates = Vec::new();
    if let Some(explicit) = explicit_runtime_layout_path()? {
        candidates.push(explicit);
    }
    if let Ok(executable) = std::env::current_exe()
        && let Some(directory) = executable.parent()
    {
        candidates.push(directory.join(RUNTIME_LAYOUT_FILENAME));
        // Distributed service binaries live in bin while the manifest owns the parent layout.
        // 发行服务程序位于 bin，清单拥有其父级布局。
        if let Some(root) = directory.parent() {
            candidates.push(root.join(RUNTIME_LAYOUT_FILENAME));
        }
    }
    if cfg!(debug_assertions) {
        // Debug builds read the manifest the development scripts generate in output/.
        // 调试构建读取开发脚本在 output/ 中生成的清单。
        candidates.push(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("..")
                .join("..")
                .join("output")
                .join(RUNTIME_LAYOUT_FILENAME),
        );
    }
    Ok(candidates)
}

/// Reads the first present manifest together with the exact path it was read from.
/// 读取首个存在的清单，并同时返回其被读取的精确路径。
///
/// # Returns
/// 返回值
/// The validated manifest and its path, or a diagnostic naming every path that was tried.
/// 返回已校验清单及其路径；否则返回列出全部已尝试路径的诊断。
pub fn read_runtime_layout_manifest_with_path() -> Result<(RuntimeLayoutManifest, PathBuf), String>
{
    let mut tried = Vec::new();
    for candidate in runtime_layout_candidates()? {
        if candidate.is_file() {
            let manifest = read_runtime_layout_manifest_from(&candidate)?;
            return Ok((manifest, candidate));
        }
        tried.push(candidate.display().to_string());
    }
    Err(format!(
        "no runtime layout manifest was found; tried {}",
        tried.join(", ")
    ))
}

/// Returns the manifest directory that roots every relative layout entry.
/// 返回作为全部相对布局条目根的清单目录。
pub fn runtime_layout_root(manifest_path: &Path) -> Result<PathBuf, String> {
    manifest_path
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| {
            format!(
                "runtime layout manifest {} has no parent directory",
                manifest_path.display()
            )
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Builds one complete manifest fixture with every required field.
    /// 构建一份包含全部必填字段的完整清单夹具。
    fn manifest_fixture() -> RuntimeLayoutManifest {
        RuntimeLayoutManifest {
            schema_version: RUNTIME_LAYOUT_SCHEMA_VERSION,
            profile: String::from("release"),
            service_executable: String::from("bin/vulcan-code-service.exe"),
            desktop_executable: String::from("desktop/vulcan-code-desktop.exe"),
            desktop_entry: String::from("desktop/resources/app/main.js"),
            tui_executable: String::from("bin/vulcan-tui.exe"),
            browser_host_entry: String::from("desktop/resources/app/browser-host/main.js"),
            browser_host_executable: String::from("dependencies/runtimes/node/node.exe"),
            chromium_executable: Some(String::from("browser/chromium/chrome.exe")),
            webui_root: String::from("webui"),
            runtime_version: String::from("0.1.0"),
            platform: String::from("win32"),
            architecture: String::from("x64"),
            capabilities: vec![String::from("browser-host")],
        }
    }

    /// Verifies the manifest round-trips through the documented camelCase wire shape.
    /// 验证清单以文档规定的 camelCase 线协议形状往返。
    #[test]
    fn manifest_round_trips_through_camel_case_json() {
        let body = serde_json::to_string(&manifest_fixture()).expect("serialize manifest");
        assert!(body.contains(&format!(
            "\"schemaVersion\":{RUNTIME_LAYOUT_SCHEMA_VERSION}"
        )));
        assert!(body.contains("\"desktopEntry\":"));
        let parsed: RuntimeLayoutManifest = serde_json::from_str(&body).expect("parse manifest");
        assert_eq!(parsed, manifest_fixture());
        assert!(validate_manifest(&parsed).is_ok());
    }

    /// Verifies an unsupported schema version is rejected instead of guessed.
    /// 验证不支持的架构版本被拒绝，而不是被猜测。
    #[test]
    fn unsupported_schema_version_is_rejected() {
        let mut manifest = manifest_fixture();
        manifest.schema_version = 99;
        assert!(validate_manifest(&manifest).is_err());
    }

    /// Verifies a missing required field fails strict parsing.
    /// 验证缺失必填字段时严格解析失败。
    #[test]
    fn missing_required_field_is_rejected() {
        let body = serde_json::json!({
            "schemaVersion": 1,
            "profile": "release"
        })
        .to_string();
        assert!(serde_json::from_str::<RuntimeLayoutManifest>(&body).is_err());
    }

    /// Verifies relative entries resolve inside the root and escapes are refused.
    /// 验证相对条目解析到根内，且逃逸被拒绝。
    #[test]
    fn layout_entries_stay_inside_the_release_root() {
        let root = Path::new("C:/release");
        assert_eq!(
            resolve_layout_entry(root, "bin/service.exe").expect("relative entry"),
            root.join("bin").join("service.exe")
        );
        assert!(resolve_layout_entry(root, "../outside.exe").is_err());
        assert!(resolve_layout_entry(root, "/absolute.exe").is_err());
        assert!(resolve_layout_entry(root, "").is_err());
    }

    /// Verifies an explicit override must be an absolute path.
    /// 验证显式覆盖路径必须是绝对路径。
    #[test]
    fn explicit_override_requires_an_absolute_path() {
        assert_eq!(
            explicit_runtime_layout_path_from(None).expect("unset"),
            None
        );
        assert!(explicit_runtime_layout_path_from(Some("")).is_err());
        assert!(explicit_runtime_layout_path_from(Some("relative/layout.json")).is_err());
        // absolute uses the host's own absolute form; a drive path is relative on Unix.
        // absolute 使用宿主自身的绝对路径形式；盘符路径在 Unix 上是相对路径。
        let absolute = if cfg!(windows) {
            "C:/release/runtime-layout.json"
        } else {
            "/release/runtime-layout.json"
        };
        assert_eq!(
            explicit_runtime_layout_path_from(Some(absolute)).expect("absolute override"),
            Some(PathBuf::from(absolute))
        );
    }
}
