import React from "react";
import { StreamPlaceholder } from "@/components/ui/stream-placeholder";

import type { ConversationSessionResourceCatalogV1 } from "@/state/conversation-session-resources-v1";
import type {
  GeneratedResourceKind,
  GeneratedResourceRef,
  ResourceId,
} from "@/service/conversation-event-window-store";
import type { AvailableSessionResourceV1 } from "@/service/conversation-session-resources-v1";

/** Props for one ordered V1 user-input resource list.
 * 一个有序 V1 用户输入资源列表的属性。 */
export interface ConversationV1ResourceListProps {
  /** Ordered project resource identities persisted by the user-input event.
   * 用户输入事件持久化的有序项目资源身份。 */
  resourceIds: readonly ResourceId[];
  /** Owner-bound metadata and controlled content URL resolver.
   * 绑定所有者的元数据与受控内容 URL 解析器。 */
  catalog: ConversationSessionResourceCatalogV1 | null;
}

/** Renders project resources in event order without reading legacy attachment records.
 * 按事件顺序渲染项目资源，且不读取旧附件记录。
 *
 * @param props ordered resource ids plus their owner-bound catalog.
 *              有序资源 ID 及其绑定所有者的目录。
 * @returns one explicit loading, failure, missing, or available resource surface.
 *          一个显式的加载、失败、缺失或可用资源界面。 */
export function ConversationV1ResourceList(props: ConversationV1ResourceListProps) {
  if (props.resourceIds.length === 0) {
    return null;
  }
  if (props.catalog === null || props.catalog.status === "loading") {
    return <StreamPlaceholder className="conversation-v1-resources-state" label="正在读取附件信息…" shape="tiles" count={2} />;
  }
  if (props.catalog.status === "failed") {
    return (
      <div className="conversation-v1-resources-state conversation-v1-resources-error">
        附件信息读取失败：{props.catalog.error}
      </div>
    );
  }
  const catalog = props.catalog;
  return (
    <ul className="conversation-v1-resources" data-resource-count={props.resourceIds.length}>
      {props.resourceIds.map((currentResourceId, index) => {
        const summary = catalog.resources.get(currentResourceId);
        const key = `${currentResourceId}:${index}`;
        if (summary === undefined) {
          return (
            <li className="conversation-v1-resource conversation-v1-resource-missing" key={key}>
              [MISSING PROJECT RESOURCE]
            </li>
          );
        }
        if (summary.availability === "missing") {
          return (
            <li className="conversation-v1-resource conversation-v1-resource-missing" key={key}>
              {summary.placeholder}
            </li>
          );
        }
        return (
          <ConversationV1AvailableResource
            catalog={catalog}
            key={key}
            summary={summary}
          />
        );
      })}
    </ul>
  );
}

/** Props for ordered project resources generated by one persisted tool call.
 * 一次持久化工具调用生成的有序项目资源属性。 */
export interface ConversationV1GeneratedResourceListProps {
  /** Ordered generated-resource references committed with the terminal tool event.
   * 随终态工具事件提交的有序生成资源引用。 */
  resources: readonly GeneratedResourceRef[];
  /** Owner-bound metadata and controlled content URL resolver.
   * 绑定所有者的元数据与受控内容 URL 解析器。 */
  catalog: ConversationSessionResourceCatalogV1 | null;
}

/** Renders generated resources only from their durable ResourceIds and typed kinds.
 * 仅从生成资源的持久化 ResourceId 与强类型类型渲染资源。
 *
 * @param props ordered generated references plus their owner-bound catalog.
 *              有序生成资源引用及其绑定所有者的目录。
 * @returns one explicit generated-resource section or null when no resource exists.
 *          一个显式生成资源区域；没有资源时返回 null。 */
export function ConversationV1GeneratedResourceList(
  props: ConversationV1GeneratedResourceListProps,
) {
  if (props.resources.length === 0) {
    return null;
  }
  if (props.catalog === null || props.catalog.status === "loading") {
    return <StreamPlaceholder className="conversation-v1-resources-state" label="正在读取生成资源…" shape="tiles" count={2} />;
  }
  if (props.catalog.status === "failed") {
    return (
      <div className="conversation-v1-resources-state conversation-v1-resources-error">
        生成资源读取失败：{props.catalog.error}
      </div>
    );
  }
  const catalog = props.catalog;
  return (
    <section className="conversation-v1-generated-resources" data-generated-resource-count={props.resources.length}>
      <div className="v1-tool-card-section-title">生成资源</div>
      <ul className="conversation-v1-resources">
        {props.resources.map((reference, index) => {
          const summary = catalog.resources.get(reference.resource_id);
          const previewSummary = reference.preview_resource_id === undefined
            ? undefined
            : catalog.resources.get(reference.preview_resource_id);
          const key = `${reference.resource_id}:${reference.preview_resource_id ?? "none"}:${index}`;
          if (summary === undefined || summary.availability === "missing") {
            return (
              <li className="conversation-v1-resource conversation-v1-resource-missing" key={key}>
                {summary?.availability === "missing"
                  ? summary.placeholder
                  : "[MISSING PROJECT RESOURCE]"}
              </li>
            );
          }
          return (
            <ConversationV1AvailableResource
              catalog={catalog}
              generatedKind={reference.kind}
              key={key}
              previewMissing={reference.preview_resource_id !== undefined
                && (previewSummary === undefined || previewSummary.availability === "missing")}
              previewSummary={previewSummary?.availability === "available" ? previewSummary : undefined}
              summary={summary}
            />
          );
        })}
      </ul>
    </section>
  );
}

/** Props for one available immutable resource row.
 * 单个可用不可变资源行的属性。 */
interface ConversationV1AvailableResourceProps {
  /** Exact available metadata projection.
   * 精确的可用元数据投影。 */
  summary: AvailableSessionResourceV1;
  /** Exact owner-bound content URL resolver.
   * 精确绑定所有者的内容 URL 解析器。 */
  catalog: ConversationSessionResourceCatalogV1;
  /** Optional durable semantic kind for a tool-generated resource.
   * 工具生成资源的可选持久化语义类型。 */
  generatedKind?: GeneratedResourceKind;
  /** Optional available preview resource referenced by the same tool event.
   * 同一工具事件引用的可选可用预览资源。 */
  previewSummary?: AvailableSessionResourceV1;
  /** Whether an explicitly referenced preview resource is missing.
   * 明确引用的预览资源是否缺失。 */
  previewMissing?: boolean;
}

/** Renders one available resource with optional safe raster preview.
 * 渲染一个可用资源及其可选安全光栅预览。
 *
 * @param props available resource metadata and owner-bound resolver.
 *              可用资源元数据与绑定所有者的解析器。
 * @returns one linked resource row or an explicit unavailable-content row.
 *          一个带链接的资源行或显式的内容不可用行。 */
function ConversationV1AvailableResource(props: ConversationV1AvailableResourceProps) {
  let contentUrl: string;
  try {
    contentUrl = props.catalog.contentUrl(props.summary.resource_id);
  } catch (error) {
    return (
      <li
        className="conversation-v1-resource conversation-v1-resource-unavailable"
        title={error instanceof Error ? error.message : String(error)}
      >
        <strong>{props.summary.original_name}</strong>
        <span>内容服务不可用</span>
        <details>
          <summary>错误详情</summary>
          <pre>{error instanceof Error ? error.message : String(error)}</pre>
        </details>
      </li>
    );
  }
  let previewUrl: string | null = null;
  // previewError retains the original resolver failure for keyboard-accessible inspection.
  // previewError 保留解析器原始失败，以便通过键盘查看。
  let previewError: string | null = null;
  if (props.previewSummary !== undefined) {
    try {
      previewUrl = props.catalog.contentUrl(props.previewSummary.resource_id);
    } catch (error) {
      previewError = error instanceof Error ? error.message : String(error);
    }
  }
  const rasterPreview = props.summary.mime?.startsWith("image/") === true
    && props.summary.mime !== "image/svg+xml";
  const generatedMedia = generatedResourceMedia(
    props.generatedKind,
    contentUrl,
    previewUrl,
    props.summary.original_name,
    rasterPreview,
  );
  return (
    <li
      className="conversation-v1-resource conversation-v1-resource-available"
      data-generated-resource-kind={props.generatedKind}
      data-preview-resource-missing={props.previewMissing || previewError !== null || undefined}
    >
      {generatedMedia}
      <a href={contentUrl} rel="noreferrer" target="_blank">
        {generatedMedia === null && props.generatedKind === undefined && rasterPreview ? (
          <img alt={props.summary.original_name} loading="lazy" src={contentUrl} />
        ) : null}
        <span>
          <strong>{props.summary.original_name}</strong>
          <small>{resourceDescription(props.summary)}</small>
          {props.previewMissing || previewError !== null ? <small>预览资源不可用</small> : null}
        </span>
      </a>
      {previewError !== null ? (
        <details>
          <summary>错误详情</summary>
          <pre>{previewError}</pre>
        </details>
      ) : null}
    </li>
  );
}

/** Builds one safe inline preview from persisted kind and controlled URLs only.
 * 仅从持久化类型与受控 URL 构建一个安全内联预览。
 *
 * @param kind optional generated-resource semantic kind.
 *             可选的生成资源语义类型。
 * @param contentUrl controlled primary resource URL.
 *                   受控主资源 URL。
 * @param previewUrl controlled preview resource URL when present.
 *                   存在时的受控预览资源 URL。
 * @param altText accessible resource label.
 *                可访问资源标签。
 * @param primaryIsRaster whether the primary resource is a safe raster image.
 *                        主资源是否为安全光栅图像。
 * @returns one media node or null for link-only resource kinds.
 *          一个媒体节点；仅链接资源类型返回 null。 */
function generatedResourceMedia(
  kind: GeneratedResourceKind | undefined,
  contentUrl: string,
  previewUrl: string | null,
  altText: string,
  primaryIsRaster: boolean,
): React.ReactNode {
  if (previewUrl !== null) {
    return <img alt={`${altText} 预览`} loading="lazy" src={previewUrl} />;
  }
  if (kind === "image" && primaryIsRaster) {
    return <img alt={altText} loading="lazy" src={contentUrl} />;
  }
  if (kind === "video") {
    return <video aria-label={altText} controls preload="metadata" src={contentUrl} />;
  }
  if (kind === "audio") {
    return <audio aria-label={altText} controls preload="metadata" src={contentUrl} />;
  }
  return null;
}

/** Formats one available resource description from authoritative metadata only.
 * 仅从权威元数据格式化一个可用资源描述。
 *
 * @param summary available project resource metadata.
 *                可用项目资源元数据。
 * @returns a compact MIME and byte-size label.
 *          紧凑的 MIME 与字节大小标签。 */
function resourceDescription(summary: AvailableSessionResourceV1): string {
  const mime = summary.mime ?? "application/octet-stream";
  return `${mime} · ${formatByteSize(summary.size)}`;
}

/** Formats one exact safe-integer byte size without changing its stored value.
 * 在不改变存储值的情况下格式化一个精确安全整数字节大小。
 *
 * @param size exact byte count.
 *             精确字节数。
 * @returns a compact binary-unit display label.
 *          紧凑的二进制单位展示标签。 */
function formatByteSize(size: number): string {
  if (size < 1024) {
    return `${size} B`;
  }
  if (size < 1024 * 1024) {
    return `${(size / 1024).toFixed(1)} KiB`;
  }
  if (size < 1024 * 1024 * 1024) {
    return `${(size / (1024 * 1024)).toFixed(1)} MiB`;
  }
  return `${(size / (1024 * 1024 * 1024)).toFixed(1)} GiB`;
}
