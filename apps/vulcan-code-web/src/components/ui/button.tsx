// Button renders the shared ordinary action control.
// Button 渲染共享的普通操作控件。
function Button({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof buttonVariants> & {
    asChild?: boolean
  }) {
  const Comp = asChild ? Slot.Root : "button"

  return (
    <Comp
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

// IconButtonSize identifies the four approved square action dimensions.
// IconButtonSize 标识四种允许使用的方形操作尺寸。
type IconButtonSize = "xs" | "sm" | "md" | "lg"

// IconButtonProps defines a semantic icon-only action without exposing text-button sizes.
// IconButtonProps 定义语义化的纯图标操作，并隐藏文本按钮尺寸。
interface IconButtonProps extends Omit<React.ComponentProps<typeof Button>, "size"> {
  // Square size selected from the unified icon-button scale.
  // 从统一图标按钮尺寸体系中选择的方形尺寸。
  size?: IconButtonSize
}

// iconButtonSizeMap maps semantic square sizes to the shared Button recipes.
// iconButtonSizeMap 将语义方形尺寸映射到共享 Button 配方。
const iconButtonSizeMap: Record<IconButtonSize, "icon-xs" | "icon-sm" | "icon" | "icon-lg"> = {
  xs: "icon-xs",
  sm: "icon-sm",
  md: "icon",
  lg: "icon-lg",
}

// IconButton renders icon-only actions through the same visual and state system as Button.
// IconButton 通过与 Button 相同的视觉和状态体系渲染纯图标操作。
function IconButton({ size = "sm", variant = "ghost", ...props }: IconButtonProps) {
  return <Button size={iconButtonSizeMap[size]} variant={variant} {...props} />
}

export { Button, IconButton, buttonVariants }
export type { IconButtonProps, IconButtonSize }
