// SelectContentPlacement defines automatic or intentionally fixed vertical placement.
// SelectContentPlacement 定义自动或明确固定的垂直展开方向。
type SelectContentPlacement = "auto" | "top" | "bottom"

// SelectContentProps exposes content options and one controlled placement contract.
// SelectContentProps 开放内容配置与一个受控的定位契约。
interface SelectContentProps extends Omit<
  React.ComponentProps<typeof SelectPrimitive.Content>,
  "align" | "avoidCollisions" | "collisionPadding" | "position" | "side" | "sideOffset"
> {
  // Automatic placement prefers bottom and flips when needed; fixed modes never flip.
  // 自动定位优先向下并在空间不足时翻转；固定模式不会翻转。
  placement?: SelectContentPlacement
}

// SelectContent prefers the lower side and flips above only when viewport space is insufficient.
// SelectContent 优先在触发框下方展开，仅当视口空间不足时自动翻转到上方。
function SelectContent({
  className,
  children,
  placement = "auto",
  ...props
}: SelectContentProps) {
  // preferredSide keeps ordinary forms downward while allowing toolbar-specific upward menus.
  // preferredSide 让普通表单优先向下，同时允许工具栏专用菜单固定向上。
  const preferredSide = placement === "top" ? "top" : "bottom"
  // avoidCollisions is enabled only for automatic placement so explicit directions stay stable.
  // avoidCollisions 仅在自动定位时启用，使显式方向保持稳定。
  const avoidCollisions = placement === "auto"
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        className={cn("relative z-50 max-h-(--radix-select-content-available-height) min-w-36 origin-(--radix-select-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-100 data-[side=bottom]:slide-in-from-top-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95", className)}
        position="popper"
        side={preferredSide}
        align="start"
        sideOffset={4}
        avoidCollisions={avoidCollisions}
        collisionPadding={8}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          data-position="popper"
          className="w-full min-w-(--radix-select-trigger-width)"
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

