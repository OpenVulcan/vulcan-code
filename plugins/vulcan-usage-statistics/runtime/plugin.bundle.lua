-- Add two arbitrary-precision non-negative integer strings.
-- 对两个任意精度非负整数字符串求和。
--
-- left and right are normalized or zero-padded digit strings.
-- left 与 right 是规范化或补零后的数字字符串。
-- Returns their exact integer sum as a canonical digit string.
-- 返回规范数字字符串形式的精确整数和。
local function add_unsigned_integers(left, right)
    left = normalize_unsigned_integer(left)
    right = normalize_unsigned_integer(right)
    local left_index = #left
    local right_index = #right
    local carry = 0
    local reversed = {}
    while left_index > 0 or right_index > 0 or carry > 0 do
        local left_digit = 0
        if left_index > 0 then
            left_digit = string.byte(left, left_index) - 48
            left_index = left_index - 1
        end
        local right_digit = 0
        if right_index > 0 then
            right_digit = string.byte(right, right_index) - 48
            right_index = right_index - 1
        end
        local total = left_digit + right_digit + carry
        reversed[#reversed + 1] = tostring(total % 10)
        carry = math.floor(total / 10)
    end
    local digits = {}
    for index = #reversed, 1, -1 do
        digits[#digits + 1] = reversed[index]
    end
    return table.concat(digits)
end

-- Multiply two arbitrary-precision non-negative integer strings.
-- 对两个任意精度非负整数字符串求积。
--
-- left and right are digit-only strings.
-- left 与 right 是只包含数字的字符串。
-- Returns their exact integer product as a canonical digit string.
-- 返回规范数字字符串形式的精确整数积。
local function multiply_unsigned_integers(left, right)
    left = normalize_unsigned_integer(left)
    right = normalize_unsigned_integer(right)
    if left == "0" or right == "0" then
        return "0"
    end
    local digits = {}
    for index = 1, #left + #right do
        digits[index] = 0
    end
    for left_index = #left, 1, -1 do
        local left_digit = string.byte(left, left_index) - 48
        for right_index = #right, 1, -1 do
            local right_digit = string.byte(right, right_index) - 48
            local position = left_index + right_index
            digits[position] = digits[position] + left_digit * right_digit
        end
    end
    for position = #digits, 2, -1 do
        local carry = math.floor(digits[position] / 10)
        digits[position] = digits[position] % 10
        digits[position - 1] = digits[position - 1] + carry
    end
    local output = {}
    local started = false
    for _, digit in ipairs(digits) do
        if digit ~= 0 or started then
            started = true
            output[#output + 1] = tostring(digit)
        end
    end
    return table.concat(output)
end

-- Parse one non-negative catalog price into integer digits and a decimal scale.
-- 将一个非负目录价格解析为整数数字与十进制小数位数。
--
-- value is one exact decimal string from the plugin-owned catalog.
-- value 是插件自有价目表中的一个精确十进制字符串。
-- Returns canonical digits followed by the fractional scale.
-- 返回规范数字以及小数位数。
local function parse_catalog_decimal(value)
    if type(value) ~= "string" then
        error("Vulcan Usage Statistics catalog price must be a string")
    end
    local whole, fraction = value:match("^(%d+)%.(%d+)$")
    if whole == nil then
        whole = value:match("^(%d+)$")
        fraction = ""
    end
    if whole == nil then
        error("Vulcan Usage Statistics catalog price is not a non-negative decimal: " .. value)
    end
    return normalize_unsigned_integer(whole .. fraction), #fraction
end

-- Convert one SQLite JSON integer Token count into exact decimal digits.
-- 将一个 SQLite JSON 整数 Token 数转换为精确十进制数字。
--
-- value is one nullable Token fact.
-- value 是一个可为空的 Token 事实。
-- Returns nil for unknown data or exact digits for a non-negative integer.
-- 对未知数据返回 nil，对非负整数返回精确数字。
local function token_digits(value)
    if value == nil or value == vulcan.json.null then
        return nil
    end
    if type(value) ~= "number" or value % 1 ~= 0 or value < 0 or value > 9007199254740991 then
        error("Vulcan Usage Statistics requires non-negative integer Token facts")
    end
    return string.format("%.0f", value)
end

-- Render exact scaled integer digits as a canonical decimal string.
-- 将精确的缩放整数数字渲染为规范十进制字符串。
--
-- digits is an unsigned integer and scale is its fractional digit count.
-- digits 是无符号整数，scale 是其小数位数。
-- Returns an exact decimal string without insignificant trailing zeros.
-- 返回不含无意义尾零的精确十进制字符串。
local function format_scaled_decimal(digits, scale)
    digits = normalize_unsigned_integer(digits)
    if scale == 0 then
        return digits
    end
    if #digits <= scale then
        digits = string.rep("0", scale - #digits + 1) .. digits
    end
    local split = #digits - scale
    local whole = digits:sub(1, split)
    local fraction = digits:sub(split + 1):gsub("0+$", "")
    if fraction == "" then
        return whole
    end
    return whole .. "." .. fraction
end

-- Estimate one row from exact Token facts and one exact catalog match.
-- 使用精确 Token 事实与一个精确目录匹配估算一行。
--
-- row contains the token-only core projection.
