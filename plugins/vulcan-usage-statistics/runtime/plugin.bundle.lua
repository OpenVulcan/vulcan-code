        }
        terms[#terms + 1] = term
        maximum_scale = math.max(maximum_scale, term.scale)
        row.pricingDetails.dimensions[#row.pricingDetails.dimensions + 1] = {
            tokenField = spec.token_field,
            perMillion = spec.price,
            cost = tokens == nil and price_digits ~= "0" and vulcan.json.null
                or format_scaled_decimal(term.digits, term.scale),
        }
    end

    if incomplete then
        row.estimatedCost = vulcan.json.null
        row.estimatedCurrency = vulcan.json.null
        row.pricingMatchStatus = "incomplete_usage"
        row.pricingRevision = pricing_revision
        row.pricingSourceId = pricing_source_id
        return row
    end

    local total_digits = "0"
    for _, term in ipairs(terms) do
        local aligned_digits = term.digits .. string.rep("0", maximum_scale - term.scale)
        total_digits = add_unsigned_integers(total_digits, aligned_digits)
    end
    row.estimatedCost = format_scaled_decimal(total_digits, maximum_scale)
    row.estimatedCurrency = DEFAULT_PRICING_CATALOG.currency
    row.pricingMatchStatus = exact_match_status
    row.pricingRevision = pricing_revision
    row.pricingSourceId = pricing_source_id
    return row
end

-- Count exact model overrides without depending on Lua table iteration order.
-- 统计精确模型覆盖数量，且不依赖 Lua 表迭代顺序。
--
-- model_overrides is the schema-validated plugin configuration map.
-- model_overrides 是通过 Schema 校验的插件配置映射。
-- Returns the number of configured model identities.
-- 返回已配置模型标识的数量。
local function model_override_count(model_overrides)
    local count = 0
    for _ in pairs(model_overrides) do
        count = count + 1
    end
    return count
end

-- Project plugin settings together with the sorted default catalog model list.
-- 投影插件设置以及排序后的默认目录模型列表。
--
-- config is the complete schema-validated plugin configuration.
-- config 是完整且通过 Schema 校验的插件配置。
-- Returns the settings action result consumed by the mounted UI.
-- 返回挂载界面消费的设置 Action 结果。
local function settings_projection(config)
    local catalog_models = vulcan.json.array()
    for model_id, pricing in pairs(DEFAULT_PRICING_CATALOG.models) do
        catalog_models[#catalog_models + 1] = {
            modelId = model_id,
            prices = {
                inputPerMillion = pricing.input_per_million,
                outputPerMillion = pricing.output_per_million,
                cacheReadPerMillion = pricing.cache_read_per_million,
                cacheWritePerMillion = pricing.cache_write_per_million,
            },
        }
    end
    table.sort(catalog_models, function(left, right)
        return left.modelId < right.modelId
    end)
    return {
        modelOverrides = config.modelOverrides,
        catalogModels = catalog_models,
    }
end

-- Load the authoritative Provider usage dashboard directly from system VLDB.
-- 直接从系统 VLDB 加载权威 Provider 用量仪表盘。
--
-- Returns one schema-validated dashboard projection.
-- 返回一个通过 Schema 校验的仪表盘投影。
local function load_dashboard(input)
    -- Explicit timestamps are one ordered interval; never silently replace malformed boundaries.
    -- 显式时间戳必须组成有序区间；不静默替换错误边界。
    if input.startAtMs ~= nil and input.endAtMs <= input.startAtMs then
        error("The end time must be later than the start time")
    end
    -- Read the commit revision before any paginated aggregate is consumed.
    -- 消费任何分页聚合前读取提交版本。
    -- The host changes this revision in the same transaction that replaces daily rows.
    -- 宿主在替换每日记录的同一事务中更新此版本。
    local initial_revision_rows = sqlite_query([[
SELECT COALESCE(MAX(CAST(meta_value AS INTEGER)), 0) AS dashboardRevision
FROM provider_usage_meta WHERE meta_key = 'aggregate_revision';
]])
    local initial_revision = initial_revision_rows[1].dashboardRevision
    -- view selects required projections; omitted arguments retain the complete legacy response.
    -- view 选择所需投影；参数省略时保留完整旧响应。
    local view = input.view or "all"
    -- Page projections read only their requested table and count, retaining the revision guard.
    -- 分页投影仅读取请求的表格及数量，并保留修订一致性检查。
    local page_only = view == "daily-page" or view == "recent-page" or view == "detail-pages"
    -- config and known_models bound cost aggregation to catalog and configured model identities.
    -- config 与 known_models 将费用聚合限制在目录与已配置模型身份内。
    local config = read_config()
    local known_models = {}
    for model_id in pairs(DEFAULT_PRICING_CATALOG.models) do known_models[model_id] = true end
    for model_id in pairs(config.modelOverrides) do known_models[model_id] = true end
    -- priced_model_ids contains at most the catalog size plus the schema-limited override count.
    -- priced_model_ids 最多包含目录规模加 Schema 限制的覆盖数量。
    local priced_model_ids = vulcan.json.array()
    for model_id in pairs(known_models) do priced_model_ids[#priced_model_ids + 1] = model_id end
    -- filter_params bind the optional bounded range and exact consumer without SQL interpolation.
    -- filter_params 绑定可选有界范围与精确消费者，不进行 SQL 插值。
    local filter_params = {
        { kind = "int64", value = input.rangeDays or 365 },
        { kind = "string", value = input.consumerId or "" },
        { kind = "int64", value = input.dailyOffset or 0 },
        { kind = "int64", value = input.recentOffset or 0 },
        { kind = "string", value = input.modelQuery or "" },
        { kind = "string", value = input.sortOrder or "newest" },
        { kind = "string", value = vulcan.json.encode(priced_model_ids) },
        { kind = "int64", value = 0 },
        -- Select recent model pages before counting or applying the page limit; omitted callers keep all types.
        -- 在计数与分页截取之前选择最近调用的模型类别；省略参数的调用方保留全部类型。
        { kind = "string", value = input.recentModelType or "all" },
        -- Zero denotes an omitted legacy bound; explicit inputs are positive Unix milliseconds.
        -- 零表示旧调用省略边界；显式输入为正 Unix 毫秒数。
        { kind = "int64", value = input.startAtMs or 0 },
        { kind = "int64", value = input.endAtMs or 0 },
        -- An empty Provider keeps every Provider; the Provider list itself ignores this filter.
        -- 空 Provider 保留全部 Provider；Provider 列表本身不应用此筛选。
        { kind = "string", value = input.providerId or "" },
    }
    -- query binds one shared filter contract to every dashboard projection.
    -- query 为每个仪表盘投影绑定同一个筛选契约。
    -- sql is fixed source SQL; returns decoded rows from the system database.
    -- sql 是固定源码 SQL；返回系统数据库中的已解码行。
    local function query(sql)
        return sqlite_query([[
WITH scoped_attempts AS (
    SELECT * FROM provider_usage_attempts_v3
    WHERE terminal_at_ms >= CASE WHEN ?10 > 0 THEN ?10
      ELSE CAST(strftime('%s', date('now', 'localtime', '-' || (?1 - 1) || ' days'), 'utc') AS INTEGER) * 1000 END
      AND (?11 = 0 OR terminal_at_ms <= ?11)
      AND (?2 = '' OR consumer_id = ?2)
      AND (?5 = '' OR instr(lower(mapped_model), lower(?5)) > 0)
), filtered_attempts AS (
    SELECT * FROM scoped_attempts WHERE ?12 = '' OR provider_id = ?12
), filtered_daily AS (
    SELECT calendar_date, provider_id, service_entry_id, consumer_id, operation, mapped_model AS model_id,
      COUNT(*) AS attempt_count,
      SUM(CASE WHEN status = 'succeeded' THEN 1 ELSE 0 END) AS successful_attempt_count,
      SUM(CASE WHEN usage_availability IN ('partial', 'final') THEN 1 ELSE 0 END) AS reported_usage_attempt_count,
      SUM(input_tokens) AS input_tokens, SUM(uncached_input_tokens) AS uncached_input_tokens,
      SUM(cache_read_tokens) AS cache_read_tokens, SUM(cache_write_tokens) AS cache_write_tokens,
      SUM(output_tokens) AS output_tokens, SUM(reasoning_tokens) AS reasoning_tokens, SUM(total_tokens) AS total_tokens,
      COUNT(*) - COUNT(uncached_input_tokens) AS uncached_input_missing,
      COUNT(*) - COUNT(cache_read_tokens) AS cache_read_missing,
      COUNT(*) - COUNT(cache_write_tokens) AS cache_write_missing,
      COUNT(*) - COUNT(output_tokens) AS output_missing
    FROM filtered_attempts
    GROUP BY calendar_date, provider_id, service_entry_id, consumer_id, operation, mapped_model
), range_usage AS (
    SELECT provider_id, service_entry_id, consumer_id, operation, model_id,
      SUM(attempt_count) AS attempt_count, SUM(successful_attempt_count) AS successful_attempt_count,
      SUM(reported_usage_attempt_count) AS reported_usage_attempt_count,
      SUM(input_tokens) AS input_tokens, SUM(uncached_input_tokens) AS uncached_input_tokens,
      SUM(cache_read_tokens) AS cache_read_tokens, SUM(cache_write_tokens) AS cache_write_tokens,
      SUM(output_tokens) AS output_tokens, SUM(reasoning_tokens) AS reasoning_tokens, SUM(total_tokens) AS total_tokens,
      SUM(uncached_input_missing) AS uncached_input_missing, SUM(cache_read_missing) AS cache_read_missing,
      SUM(cache_write_missing) AS cache_write_missing, SUM(output_missing) AS output_missing,
      MAX(calendar_date) AS latest_date
    FROM filtered_daily
    GROUP BY provider_id, service_entry_id, consumer_id, operation, model_id
), timed_attempts AS (
    SELECT *,
      CASE WHEN terminal_at_ms >= dispatched_at_ms THEN terminal_at_ms - dispatched_at_ms END AS request_duration_ms,
      CASE WHEN first_token_at_ms >= dispatched_at_ms AND terminal_at_ms >= first_token_at_ms
        THEN first_token_at_ms - dispatched_at_ms END AS first_token_latency_ms,
      CASE WHEN first_token_at_ms >= dispatched_at_ms AND terminal_at_ms >= first_token_at_ms
        THEN terminal_at_ms - first_token_at_ms END AS output_duration_ms
    FROM filtered_attempts
), recent_model_attempts AS (
    SELECT * FROM timed_attempts
    WHERE ?9 = 'all'
       OR (?9 = 'llm' AND operation IN ('conversation', 'conversation_respond', 'compact', 'warmup')
           AND consumer_id NOT IN ('vulcan-code-permission-judge', 'vulcan-code-permission-review'))
       OR (?9 = 'embedding' AND operation = 'embedding_create')
       OR (?9 = 'rerank' AND operation = 'rerank_documents')
       OR (?9 = 'decision' AND (operation = 'decision_evaluate'
           OR consumer_id IN ('vulcan-code-permission-judge', 'vulcan-code-permission-review')))
), page_offsets AS (SELECT ?3 AS daily_offset, ?4 AS recent_offset, ?6 AS sort_order, ?7 AS priced_models, ?8 AS cost_offset)
]] .. sql, filter_params)
    end
    local model_overrides = config.modelOverrides
    local daily = (view == "all" or view == "details" or view == "providers" or view == "daily-page" or view == "detail-pages") and query([[
, daily_timing AS (
    SELECT provider_id, service_entry_id, consumer_id, operation, mapped_model AS model_id,
      AVG(request_duration_ms) AS requestDurationMs,
      AVG(first_token_latency_ms) AS firstTokenLatencyMs,
      SUM(CASE WHEN output_duration_ms > 0 AND output_tokens IS NOT NULL THEN output_duration_ms END) AS outputDurationMs,
      SUM(CASE WHEN output_duration_ms > 0 AND output_tokens IS NOT NULL THEN output_tokens END) * 1000.0 /
        SUM(CASE WHEN output_duration_ms > 0 AND output_tokens IS NOT NULL THEN output_duration_ms END) AS outputTokensPerSecond,
      COUNT(CASE WHEN output_duration_ms > 0 AND output_tokens IS NOT NULL THEN 1 END) AS timedAttemptCount
    FROM timed_attempts
    GROUP BY provider_id, service_entry_id, consumer_id, operation, mapped_model
)
SELECT provider_id AS providerId,
       service_entry_id AS serviceEntryId, consumer_id AS consumerId, operation,
       model_id AS modelId, attempt_count AS attemptCount,
       successful_attempt_count AS successfulAttemptCount,
       reported_usage_attempt_count AS reportedUsageAttemptCount,
       input_tokens AS inputTokens, uncached_input_tokens AS uncachedInputTokens,
       cache_read_tokens AS cacheReadTokens, cache_write_tokens AS cacheWriteTokens,
       output_tokens AS outputTokens, reasoning_tokens AS reasoningTokens,
       total_tokens AS totalTokens,
       COALESCE((SELECT CAST(meta_value AS INTEGER) FROM provider_usage_meta WHERE meta_key = 'aggregate_revision'), 0) AS aggregateRevision,
       requestDurationMs, firstTokenLatencyMs, outputDurationMs, outputTokensPerSecond,
       COALESCE(timedAttemptCount, 0) AS timedAttemptCount
 FROM range_usage
 LEFT JOIN daily_timing USING (provider_id, service_entry_id, consumer_id, operation, model_id)
 ORDER BY CASE WHEN ?6 = 'oldest' THEN latest_date END ASC,
          CASE WHEN ?6 = 'newest' THEN latest_date END DESC,
          provider_id, service_entry_id, consumer_id, operation, model_id
LIMIT 100 OFFSET (SELECT daily_offset FROM page_offsets);
]]) or vulcan.json.array()
    -- heatmap contains one exact aggregate per local calendar date for the selected range.
    -- heatmap 包含所选范围内的每个本地自然日精确聚合。
    local heatmap = (view == "all" or view == "overview") and query([[
, filtered AS (
    SELECT calendar_date, provider_id, model_id,
           COALESCE(total_tokens, 0) AS total_tokens,
           attempt_count, successful_attempt_count
    FROM filtered_daily
), daily AS (
    SELECT calendar_date, SUM(total_tokens) AS value,
           SUM(attempt_count) AS requests,
           SUM(successful_attempt_count) AS successes
    FROM filtered
    GROUP BY calendar_date
), ranked_models AS (
    SELECT calendar_date, provider_id, model_id,
           SUM(total_tokens) AS model_tokens,
           ROW_NUMBER() OVER (
               PARTITION BY calendar_date
               ORDER BY SUM(total_tokens) DESC, provider_id, model_id
           ) AS model_rank
    FROM filtered
    GROUP BY calendar_date, provider_id, model_id
)
SELECT d.calendar_date AS date,
       d.value AS value,
       d.requests AS requests,
       d.successes AS successes,
       r.provider_id AS topProviderName,
       r.model_id AS topModelName
FROM daily d
LEFT JOIN ranked_models r
    ON r.calendar_date = d.calendar_date AND r.model_rank = 1
ORDER BY d.calendar_date;
]]) or vulcan.json.array()
    -- series contains the top five model lines plus one stable Other line for the selected range.
    -- series 包含所选范围前五个模型折线及一个稳定的其他折线。
    local series = (view == "all" or view == "overview") and query([[
, ranked_models AS (
    SELECT provider_id, model_id,
           SUM(COALESCE(total_tokens, 0)) AS metric_value
    FROM filtered_daily
    GROUP BY provider_id, model_id
    ORDER BY metric_value DESC, provider_id, model_id
    LIMIT 5
), classified AS (
    SELECT d.calendar_date,
           CASE WHEN r.provider_id IS NULL THEN 'other'
                ELSE r.provider_id || '/' || r.model_id END AS seriesKey,
           CASE WHEN r.provider_id IS NULL THEN 'Other'
                ELSE r.provider_id || ' / ' || r.model_id END AS label,
           COALESCE(d.total_tokens, 0) AS total_tokens
    FROM filtered_daily d
    LEFT JOIN ranked_models r
        ON r.provider_id = d.provider_id AND r.model_id = d.model_id
), projected AS (
    SELECT calendar_date, seriesKey, label, SUM(total_tokens) AS value
    FROM classified
    GROUP BY calendar_date, seriesKey, label
)
SELECT calendar_date AS date, seriesKey, label, value
FROM projected
ORDER BY date, seriesKey;
]]) or vulcan.json.array()
    local recent_attempts = (view == "all" or view == "details" or view == "recent" or view == "recent-page" or view == "detail-pages") and query([[
SELECT attempts.attempt_id AS attemptId, attempts.consumer_id AS consumerId,
       attempts.operation, attempts.provider_id AS providerId,
       attempts.service_entry_id AS serviceEntryId,
       attempts.mapped_model AS modelId, attempts.transport,
       attempts.http_status AS httpStatus,
       attempts.websocket_close_code AS websocketCloseCode,
       attempts.error_category AS errorCategory, attempts.error_code AS errorCode,
        attempts.status, attempts.usage_availability AS usageAvailability,
        attempts.input_tokens AS inputTokens,
        attempts.uncached_input_tokens AS uncachedInputTokens,
        attempts.cache_read_tokens AS cacheReadTokens,
        attempts.cache_write_tokens AS cacheWriteTokens,
        attempts.output_tokens AS outputTokens,
        attempts.reasoning_tokens AS reasoningTokens,
        attempts.audio_input_tokens AS audioInputTokens,
        attempts.audio_output_tokens AS audioOutputTokens,
        attempts.total_tokens AS totalTokens,
        attempts.provider_billing_details_json AS billingDetailsJson,
        attempts.terminal_at_ms AS terminalAtMs,
        attempts.request_duration_ms AS requestDurationMs,
        attempts.first_token_latency_ms AS firstTokenLatencyMs,
        attempts.output_duration_ms AS outputDurationMs,
        CASE WHEN attempts.output_duration_ms > 0 AND attempts.output_tokens IS NOT NULL
          THEN attempts.output_tokens * 1000.0 / attempts.output_duration_ms END AS outputTokensPerSecond,
        CASE WHEN attempts.output_duration_ms > 0 AND attempts.output_tokens IS NOT NULL THEN 1 ELSE 0 END AS timedAttemptCount
 FROM recent_model_attempts AS attempts
ORDER BY CASE WHEN ?6 = 'oldest' THEN attempts.terminal_at_ms END ASC,
         CASE WHEN ?6 = 'newest' THEN attempts.terminal_at_ms END DESC, attempts.attempt_id DESC
LIMIT 50 OFFSET (SELECT recent_offset FROM page_offsets);
    ]]) or vulcan.json.array()
    for _, row in ipairs(daily) do
        attach_reference_estimate(row, model_overrides)
    end
    for _, attempt in ipairs(recent_attempts) do
        attach_reference_estimate(attempt, model_overrides)
        if attempt.billingDetailsJson == nil or attempt.billingDetailsJson == vulcan.json.null then
            attempt.billingDetails = vulcan.json.array()
        else
            attempt.billingDetails = decode_json_text(
                attempt.billingDetailsJson,
                "provider_billing_details_json"
            )
        end
        attempt.billingDetailsJson = nil
    end
    if page_only then
        -- Return only requested slices; never calculate overview costs, account snapshots or unrelated counts.
        -- 仅返回请求切片；不计算概览费用、账号快照或无关表格数量。
        local page = { view = view, aggregateRevision = initial_revision }
        if view ~= "recent-page" then
            local count_rows = query([[SELECT COUNT(*) AS count FROM range_usage;]])
            page.daily = daily
            page.dailyCount = count_rows[1].count
        end
        if view ~= "daily-page" then
            local count_rows = query([[SELECT COUNT(*) AS count FROM recent_model_attempts;]])
            page.recentAttempts = recent_attempts
            page.recentCount = count_rows[1].count
        end
        -- Capture the closing revision after both page rows and counts have been read.
        -- 在分页记录与数量均读取后捕获结束修订号。
        local page_revision_rows = sqlite_query([[
SELECT COALESCE(MAX(CAST(meta_value AS INTEGER)), 0) AS dashboardRevision,
       CAST(strftime('%s', 'now') AS INTEGER) * 1000 AS generatedAtMs
FROM provider_usage_meta WHERE meta_key = 'aggregate_revision';
]])
        if initial_revision ~= page_revision_rows[1].dashboardRevision then
            error("Vulcan Usage Statistics: statistics changed during loading; refresh to read a consistent page")
        end
        page.generatedAtMs = page_revision_rows[1].generatedAtMs
        return page
    end
    local accounts = (view == "all" or view == "maintenance") and sqlite_query([[
SELECT provider_id AS providerId, connection_id AS connectionId,
       snapshot_kind AS snapshotKind,
       endpoint_profile_revision AS endpointProfileRevision,
       payload_json AS payloadJson, observed_at_ms AS observedAtMs
FROM (
    SELECT provider_id, connection_id, snapshot_kind, endpoint_profile_revision,
           payload_json, observed_at_ms,
           ROW_NUMBER() OVER (
               PARTITION BY connection_id, snapshot_kind
               ORDER BY observed_at_ms DESC, snapshot_id DESC
           ) AS rowNumber
    FROM provider_account_usage_snapshots_v1
)
WHERE rowNumber = 1
ORDER BY providerId, connectionId, snapshotKind
LIMIT 500;
]]) or vulcan.json.array()
    for _, account in ipairs(accounts) do
        account.payload = decode_json_text(account.payloadJson, "payload_json")
        account.payloadJson = nil
    end
    -- providers lists every Provider in the scope without the Provider filter, so the selector keeps its options.
    -- providers 列出不含 Provider 筛选的作用域内全部 Provider，使选择器保留全部选项。
    local providers = (view == "all" or view == "providers") and query([[
SELECT provider_id AS providerId, COUNT(*) AS attempts,
       SUM(CASE WHEN status = 'succeeded' THEN 1 ELSE 0 END) AS successes,
       COALESCE(SUM(total_tokens), 0) AS totalTokens
FROM scoped_attempts
GROUP BY provider_id
ORDER BY attempts DESC, provider_id
LIMIT 200;
]]) or nil
    local meta_rows = query([[
SELECT CAST(strftime('%s', 'now') AS INTEGER) * 1000 AS generatedAtMs,
       (SELECT COUNT(*) FROM range_usage) AS dailyCount,
       (SELECT COUNT(*) FROM recent_model_attempts) AS recentCount,
       (SELECT json_group_array(consumer_id) FROM
           (SELECT DISTINCT consumer_id FROM provider_usage_daily_v3 ORDER BY consumer_id)) AS consumerIdsJson,
       COALESCE(MAX(CASE WHEN meta_key = 'schema_revision'
                         THEN CAST(meta_value AS INTEGER) END), 0) AS schemaRevision,
       COALESCE(MAX(CASE WHEN meta_key = 'aggregate_revision'
                         THEN CAST(meta_value AS INTEGER) END), 0) AS aggregateRevision,
       COALESCE(MAX(CASE WHEN meta_key = 'health_status'
                         THEN meta_value END), 'unknown') AS healthStatus
FROM provider_usage_meta;
]])
    local meta = meta_rows[1]
    if type(meta) ~= "table" then
        error("Vulcan Usage Statistics could not read system statistics metadata")
    end
    -- summary_rows aggregate the entire selected range, independent of detail pagination.
    -- summary_rows 聚合全部已选范围，不受明细分页影响。
    local summary_rows = query([[
SELECT COALESCE(SUM(attempt_count), 0) AS attempts,
       COALESCE(SUM(successful_attempt_count), 0) AS successes,
       COALESCE(SUM(reported_usage_attempt_count), 0) AS reported,
       COALESCE(SUM(total_tokens), 0) AS totalTokens,
       SUM(input_tokens) AS inputTokens, SUM(output_tokens) AS outputTokens,
       SUM(cache_read_tokens) AS cacheReadTokens, SUM(cache_write_tokens) AS cacheWriteTokens
FROM filtered_daily;
]])
    -- cost_rows preserve each missing-usage combination instead of converting missing values to zero.
    -- cost_rows 保留每种缺失用量组合，不把缺失值转为零。
    -- Four nullable dimensions bound this projection to sixteen groups per priced model.
    -- 四个可空维度将此投影限制为每个已定价模型最多十六组。
    -- cost_sql pages bounded groups so maximum configured overrides cannot exceed host row limits.
    -- cost_sql 对有界分组分页，确保最大配置覆盖数不会超过宿主行数限制。
    -- cost_basis treats a dimension as missing when any attempt in the row lacked it, because SUM
    -- skips NULL values and would otherwise report a partial total as complete.
    -- cost_basis 在该行任一尝试缺少某维度时将其视为缺失，因为 SUM 会跳过 NULL，否则会把部分合计报告为完整。
    local cost_sql = [[
, cost_basis AS (
    SELECT model_id,
      CASE WHEN uncached_input_missing = 0 THEN uncached_input_tokens END AS uncached_input_tokens,
      CASE WHEN cache_read_missing = 0 THEN cache_read_tokens END AS cache_read_tokens,
      CASE WHEN cache_write_missing = 0 THEN cache_write_tokens END AS cache_write_tokens,
      CASE WHEN output_missing = 0 THEN output_tokens END AS output_tokens
    FROM range_usage
    WHERE model_id IN (SELECT value FROM json_each(?7))
)
SELECT model_id AS modelId, COUNT(*) AS rowCount,
       SUM(uncached_input_tokens) AS uncachedInputTokens,
       SUM(cache_read_tokens) AS cacheReadTokens,
       SUM(cache_write_tokens) AS cacheWriteTokens,
       SUM(output_tokens) AS outputTokens
FROM cost_basis
GROUP BY model_id, uncached_input_tokens IS NULL, cache_read_tokens IS NULL,
         cache_write_tokens IS NULL, output_tokens IS NULL
ORDER BY model_id, uncached_input_tokens IS NULL, cache_read_tokens IS NULL,
         cache_write_tokens IS NULL, output_tokens IS NULL
LIMIT 1000 OFFSET (SELECT cost_offset FROM page_offsets);
]]
    -- cost_digits and cost_scale retain exact decimal arithmetic across the complete filtered range.
    -- cost_digits 与 cost_scale 在完整筛选范围内保持精确十进制运算。
    local cost_digits, cost_scale = "0", 0
    local priced_rows, incomplete_rows = 0, 0
    while true do
      local cost_rows = query(cost_sql)
      for _, row in ipairs(cost_rows) do
        attach_reference_estimate(row, model_overrides)
        if row.estimatedCost == vulcan.json.null then
            incomplete_rows = incomplete_rows + row.rowCount
        else
            -- digits and scale are exact integer components of one model subtotal.
            -- digits 与 scale 是单个模型小计的精确整数分量。
            local digits, scale = parse_catalog_decimal(row.estimatedCost)
            local next_scale = math.max(cost_scale, scale)
            cost_digits = add_unsigned_integers(
                cost_digits .. string.rep("0", next_scale - cost_scale),
                digits .. string.rep("0", next_scale - scale)
            )
            cost_scale = next_scale
            priced_rows = priced_rows + row.rowCount
        end
      end
      if #cost_rows < 1000 then break end
      filter_params[8].value = filter_params[8].value + 1000
    end
    -- Independent host queries do not share a read transaction; never publish mixed aggregate generations.
    -- 独立宿主查询不共享读取事务；绝不发布混合聚合代次。
    -- A changed revision requires an explicit reread, not an unbounded automatic retry while usage is arriving.
    -- 版本变化时要求明确重新读取，不在用量持续到达时无限自动重试。
    local completed_revision_rows = sqlite_query([[
SELECT COALESCE(MAX(CAST(meta_value AS INTEGER)), 0) AS dashboardRevision
FROM provider_usage_meta WHERE meta_key = 'aggregate_revision';
]])
    if initial_revision ~= meta.aggregateRevision
        or initial_revision ~= completed_revision_rows[1].dashboardRevision then
        error("Vulcan Usage Statistics: statistics changed during loading; refresh to read a consistent dashboard")
    end
    summary_rows[1].costs = {{
        currency = DEFAULT_PRICING_CATALOG.currency,
        amount = priced_rows > 0 and format_scaled_decimal(cost_digits, cost_scale) or vulcan.json.null,
        pricedRows = priced_rows,
        incompleteRows = incomplete_rows,
        unpricedRows = meta.dailyCount - priced_rows - incomplete_rows,
    }}
    local dashboard = {
        generatedAtMs = meta.generatedAtMs,
        view = view,
        schemaRevision = meta.schemaRevision,
        aggregateRevision = meta.aggregateRevision,
        healthStatus = meta.healthStatus,
        dailyCount = meta.dailyCount,
        recentCount = meta.recentCount,
        summary = summary_rows[1],
        consumerIds = decode_json_text(meta.consumerIdsJson, "consumerIdsJson"),
        pricingCatalog = {
            catalogId = DEFAULT_PRICING_CATALOG.catalog_id,
            revision = DEFAULT_PRICING_CATALOG.revision,
            currency = DEFAULT_PRICING_CATALOG.currency,
            entryCount = DEFAULT_PRICING_CATALOG.entry_count,
            overrideCount = model_override_count(model_overrides),
            matchingStrategy = DEFAULT_PRICING_CATALOG.matching_strategy,
        },
        daily = daily,
        heatmap = heatmap,
        series = series,
        recentAttempts = recent_attempts,
        accounts = accounts,
    }
    if providers then dashboard.providers = providers end
    return dashboard
end

