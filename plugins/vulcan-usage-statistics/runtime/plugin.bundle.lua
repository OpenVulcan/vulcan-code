-- Normalize one non-negative decimal digit string without changing its exact value.
-- 规范化一个非负十进制数字字符串，且不改变其精确值。
--
-- value is a digit-only string.
-- value 是一个只包含数字的字符串。
-- Returns a canonical digit string with at least one digit.
-- 返回至少包含一位数字的规范数字字符串。
local function normalize_unsigned_integer(value)
    if type(value) ~= "string" or value:match("^%d+$") == nil then
        error("Vulcan Usage Statistics requires an unsigned integer string")
    end
    local normalized = value:gsub("^0+", "")
