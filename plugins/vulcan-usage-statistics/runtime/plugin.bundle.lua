    local pricing = nil
    local exact_match_status = "catalog_exact"
    local pricing_revision = DEFAULT_PRICING_CATALOG.revision
    local pricing_source_id = DEFAULT_PRICING_CATALOG.catalog_id
    if configured ~= nil then
        pricing = {
            input_per_million = configured.inputPerMillion,
            output_per_million = configured.outputPerMillion,
            cache_read_per_million = configured.cacheReadPerMillion,
            cache_write_per_million = configured.cacheWritePerMillion,
        }
        exact_match_status = "override_exact"
        -- Override revision serializes every exact input so historical Token facts are visibly re-priced after edits.
        -- 覆盖修订号序列化全部精确输入，使历史 Token 事实在编辑后能够明确显示为重新估价。
        pricing_revision = table.concat({
            "plugin-config-v1",
            row.modelId,
            configured.inputPerMillion,
            configured.outputPerMillion,
            configured.cacheReadPerMillion,
            configured.cacheWritePerMillion,
        }, ":")
        pricing_source_id = "plugin.config.modelOverrides:" .. row.modelId
    else
        pricing = DEFAULT_PRICING_CATALOG.models[row.modelId]
    end
    if pricing == nil then
        row.estimatedCost = vulcan.json.null
        row.estimatedCurrency = vulcan.json.null
        row.pricingMatchStatus = "unmatched"
        row.pricingRevision = vulcan.json.null
        row.pricingSourceId = vulcan.json.null
