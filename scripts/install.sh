#!/bin/sh
# Install, upgrade, or remove Vulcan Code on Linux and macOS from release archives published beside this script.
# 从与本脚本一同发布的发行归档，在 Linux 与 macOS 上安装、升级或移除 Vulcan Code。
#
#   curl -fsSL <release-url>/install.sh | sh
#   curl -fsSL <release-url>/install.sh | sh -s -- --with-browser-dependencies
#   sh install.sh --from <url-or-directory> [--prefix <dir>] [--bin-dir <dir>]
#   sh install.sh --uninstall [--prefix <dir>] [--bin-dir <dir>]
#
# Immutable archive generations live in <prefix>/versions; <prefix>/current points at the active one,
# and the previously active generation is kept for existing processes. User data under ~/.vulcan is never touched.
# 不可变归档代际位于 <prefix>/versions；<prefix>/current 指向当前代际，并为既有进程保留上一代际。
# 本脚本从不触碰 ~/.vulcan 下的用户数据。

set -eu

# Source is the directory holding SHA256SUMS and the archives; --from selects a URL or local directory.
# Source 是存放 SHA256SUMS 与归档的位置；--from 可选择 URL 或本地目录。
Source="https://github.com/OpenVulcan/vulcan-code/releases/latest/download"
Prefix="$HOME/.local/share/vulcan-code"
BinDir="$HOME/.local/bin"
BrowserDependencies=0
Uninstall=0
# LauncherMarker identifies launchers this script owns, so foreign files of the same name are never replaced.
# LauncherMarker 标识本脚本拥有的启动器，绝不替换同名的他人文件。
LauncherMarker="# Generated by the Vulcan Code installer."
# InstallationMarker reserves only this installer's dedicated prefix and version namespace.
# InstallationMarker 仅声明此安装器专用前缀与版本命名空间的归属。
InstallationMarker=".vulcan-code-installation"
InstallationIdentity="vulcan-code-installation-v1"
# ArchiveMarker pins the complete digest even though directory names use a shorter display prefix.
# ArchiveMarker 固定完整摘要，即使目录名只使用较短的显示前缀。
ArchiveMarker=".vulcan-archive-sha256"

fail() {
    printf 'vulcan-code install: %s\n' "$*" >&2
    exit 1
}

# usage cannot read this file back: under `curl | sh` the script has no path.
# usage 不能回读本文件：在 `curl | sh` 下脚本没有路径。
usage() {
    printf '%s\n' \
        'usage: install.sh [--from <url-or-directory>] [--prefix <dir>] [--bin-dir <dir>] [--with-browser-dependencies]' \
        '       install.sh --uninstall [--prefix <dir>] [--bin-dir <dir>]'
}

while [ $# -gt 0 ]; do
    case "$1" in
        --from) [ $# -ge 2 ] || fail "--from needs a value"; Source=${2%/}; shift 2 ;;
        --prefix) [ $# -ge 2 ] || fail "--prefix needs a value"; Prefix=${2%/}; shift 2 ;;
        --bin-dir) [ $# -ge 2 ] || fail "--bin-dir needs a value"; BinDir=${2%/}; shift 2 ;;
        --with-browser-dependencies) BrowserDependencies=1; shift ;;
        --uninstall) Uninstall=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) fail "unknown option: $1" ;;
    esac
done

# Launchers embed both paths verbatim, so they must be absolute and free of shell-active characters.
# 启动器原样嵌入这两个路径，因此必须为绝对路径且不含 shell 特殊字符。
for Path in "$Prefix" "$BinDir"; do
    case "$Path" in
        /*) ;;
        *) fail "paths must be absolute: $Path" ;;
    esac
    case "$Path" in
        *[\"\$\`\\]*) fail "paths must not contain quotes, dollar signs, backquotes, or backslashes: $Path" ;;
    esac
done

case "$(uname -s)" in
    Linux) Os=linux ;;
    Darwin) Os=macos ;;
    *) fail "unsupported operating system $(uname -s); Windows uses the zip archive" ;;
esac
Machine=$(uname -m)
case "$Machine" in
    x86_64|amd64) Arch=x64 ;;
    aarch64|arm64) Arch=arm64 ;;
    *) fail "unsupported architecture $Machine; release archives exist for x64 and arm64" ;;
esac
# A Rosetta shell reports x86_64 on Apple silicon; the native arm64 build is the right one there.
# Rosetta 下的 shell 在 Apple 芯片上报告 x86_64；此时应安装原生 arm64 版本。
if [ "$Os" = macos ] && [ "$Arch" = x64 ] && [ "$(sysctl -n sysctl.proc_translated 2>/dev/null || true)" = 1 ]; then
    Arch=arm64
fi
Platform="$Os-$Arch"

# UnitPath is the systemd user unit vulcan-code-service --install-user-service writes for release builds.
# UnitPath 是 release 构建执行 vulcan-code-service --install-user-service 时写入的 systemd 用户单元。
UnitPath="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/vulcan-code.service"

# owns_unit succeeds when the registered unit runs a service from this prefix, never another installation's.
# owns_unit 仅在已注册单元运行本前缀中的服务时成功，绝不涉及其他安装。
owns_unit() {
    [ "$Os" = linux ] && [ -f "$UnitPath" ] && [ -d "$Prefix" ] || return 1
    PrefixReal=$(CDPATH= cd "$Prefix" && pwd -P)
    grep -F "$PrefixReal/versions/" "$UnitPath" >/dev/null 2>&1
}

# layout_entry reads one relative path from a pretty-printed runtime layout and rejects escaping values.
# layout_entry 从格式化的运行时布局读取一个相对路径，并拒绝逃逸值。
layout_entry() {
    Value=$(sed -n 's/^[[:space:]]*"'"$2"'":[[:space:]]*"\([^"]*\)".*/\1/p' "$1/runtime-layout.json")
    case "$Value" in
        ""|/*|*..*|*[\"\$\`\\]*) fail "the runtime layout in $1 has an invalid $2" ;;
    esac
    printf '%s' "$Value"
}

# remove_launcher deletes one launcher only when this script generated it.
# remove_launcher 仅删除本脚本生成的启动器。
remove_launcher() {
    if [ -f "$BinDir/$1" ] && grep -F "$LauncherMarker" "$BinDir/$1" >/dev/null 2>&1; then
        rm -f "$BinDir/$1"
    fi
}

# validate_prefix checks ownership before any install, prune, launcher removal, or uninstall.
# validate_prefix 在安装、裁剪、移除启动器或卸载之前检查归属。
# A missing marker is accepted only for a new empty installation; uninstall always requires it.
# 缺少标记时仅允许在新的空目录安装；卸载始终要求存在标记。
validate_prefix() {
    [ ! -L "$Prefix" ] || fail "the installation prefix must not be a symbolic link: $Prefix"
    if [ -e "$Prefix" ]; then
        [ -d "$Prefix" ] || fail "the installation prefix is not a directory: $Prefix"
    fi
    [ ! -L "$Prefix/$InstallationMarker" ] || fail "the installation marker must not be a symbolic link"
    if [ -f "$Prefix/$InstallationMarker" ]; then
        [ "$(cat "$Prefix/$InstallationMarker")" = "$InstallationIdentity" ] || fail "unrecognized installation marker in $Prefix"
        [ ! -L "$Prefix/versions" ] || fail "the owned versions directory must not be a symbolic link"
        [ ! -e "$Prefix/versions" ] || [ -d "$Prefix/versions" ] || fail "the owned versions path is not a directory"
        [ ! -e "$Prefix/current" ] || [ -L "$Prefix/current" ] || fail "the owned current path is not a symbolic link"
    else
        [ "$Uninstall" != 1 ] || fail "refusing to uninstall an unowned directory: $Prefix"
        if [ -d "$Prefix" ] && [ -n "$(ls -A "$Prefix")" ]; then
            fail "refusing to install into a nonempty unowned directory: $Prefix"
        fi
    fi
}

validate_prefix

if [ "$Uninstall" = 1 ]; then
    if owns_unit; then
        "$Prefix/current/$(layout_entry "$Prefix/current" serviceExecutable)" --uninstall-user-service \
            || fail "could not remove the registered user service"
    fi
    for Launcher in vulcan-code vulcan-code-service vulcan-tui; do
        remove_launcher "$Launcher"
    done
    rm -f "$Prefix/current"
    rm -rf "$Prefix/versions"
    rm -f "$Prefix/$InstallationMarker"
    # Unexpected files belong to the user; never recursively remove the prefix itself.
    # 意外文件归用户所有；绝不递归删除前缀目录本身。
    rmdir "$Prefix" 2>/dev/null || printf 'Kept directory %s and its remaining contents.\n' "$Prefix"
    printf 'Removed Vulcan Code from %s. User data in ~/.vulcan was kept.\n' "$Prefix"
    exit 0
fi

Work=$(mktemp -d "${TMPDIR:-/tmp}/vulcan-code-install.XXXXXX")
Staging=""
cleanup() {
    rm -rf "$Work"
    if [ -n "$Staging" ]; then rm -rf "$Staging"; fi
}
trap cleanup EXIT
trap 'exit 1' INT TERM

# fetch copies one published file from Source into the work directory.
# fetch 将一个已发布文件从 Source 复制到工作目录。
fetch() {
    case "$Source" in
        http://*|https://*)
            if command -v curl >/dev/null 2>&1; then
                curl -fsSL --retry 3 -o "$Work/$1" "$Source/$1" || fail "download failed: $Source/$1"
            elif command -v wget >/dev/null 2>&1; then
                wget -q -O "$Work/$1" "$Source/$1" || fail "download failed: $Source/$1"
            else
                fail "curl or wget is required"
            fi
            ;;
        *)
            [ -f "$Source/$1" ] || fail "$Source/$1 does not exist"
            cp "$Source/$1" "$Work/$1"
            ;;
    esac
}

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{ print $1 }'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{ print $1 }'
    else
        fail "sha256sum or shasum is required"
    fi
}

# The checksum index names the archive, so the installer never guesses a version or a URL pattern.
# 校验索引给出归档名称，安装脚本从不猜测版本或 URL 形式。
fetch SHA256SUMS
Assets=$(awk -v suffix="-$Platform.tar.gz" '
    $2 ~ /^vulcan-code-/ && length($2) > length(suffix) && substr($2, length($2) - length(suffix) + 1) == suffix { print $2 }
' "$Work/SHA256SUMS")
Count=$(printf '%s' "$Assets" | grep -c . || true)
[ "$Count" = 1 ] || fail "expected one $Platform archive in $Source/SHA256SUMS, found $Count"
Asset=$Assets
Expected=$(awk -v name="$Asset" '$2 == name { print $1 }' "$Work/SHA256SUMS")
fetch "$Asset"
[ "$(sha256_of "$Work/$Asset")" = "$Expected" ] || fail "checksum mismatch for $Asset"

# Name separates different builds of the same semantic version without moving an existing generation.
# Name 区分同一语义版本的不同构建，且不移动既有代际。
Name="${Asset%.tar.gz}-$(printf '%.12s' "$Expected")"
validate_prefix
mkdir -p "$Prefix"
if [ ! -f "$Prefix/$InstallationMarker" ]; then
    # Noclobber prevents another installer or file from being silently overwritten.
    # 禁止覆盖可防止静默替换另一安装器或文件。
    (set -C; printf '%s\n' "$InstallationIdentity" > "$Prefix/$InstallationMarker") \
        || fail "could not claim the installation prefix"
fi
mkdir -p "$Prefix/versions"
Previous=$(readlink "$Prefix/current" 2>/dev/null || true)
Target="$Prefix/versions/$Name"
# Unchanged marks a reinstall of the active archive: generations, the current link, and the user service stay as
# they are, while launchers are still repaired.
# Unchanged 表示重装当前归档：代际、current 链接与用户服务保持不变，但仍修复启动器。
Unchanged=0
if [ -e "$Target" ] || [ -L "$Target" ]; then
    # Never replace an existing generation, including a digest-prefix collision or an incomplete one.
    # 绝不替换既有代际，包括摘要前缀碰撞或不完整的目录。
    [ ! -L "$Target" ] && [ -d "$Target" ] && [ -f "$Target/$ArchiveMarker" ] \
        && [ "$(cat "$Target/$ArchiveMarker")" = "$Expected" ] \
        || fail "existing generation does not match the archive digest: $Target"
    Service=$(layout_entry "$Target" serviceExecutable)
    Desktop=$(layout_entry "$Target" desktopExecutable)
    Tui=$(layout_entry "$Target" tuiExecutable)
    if [ "$Previous" = "versions/$Name" ]; then
        Unchanged=1
    fi
else
    Staging=$(mktemp -d "$Prefix/versions/.staging.XXXXXX")
    tar -xzf "$Work/$Asset" -C "$Staging" || fail "could not extract $Asset"
    [ -f "$Staging/runtime-layout.json" ] || fail "$Asset has no runtime layout"
    Service=$(layout_entry "$Staging" serviceExecutable)
    Desktop=$(layout_entry "$Staging" desktopExecutable)
    Tui=$(layout_entry "$Staging" tuiExecutable)

    # Validate the new executable before publishing its immutable generation.
    # 发布不可变新代际之前校验新可执行文件。
    Description=$("$Staging/$Service" --describe 2>&1) || fail "this $Platform build cannot run on this system:
$Description"
    case "$Description" in
        *'"profile": "release"'*) ;;
        *) fail "$Asset does not contain a release build" ;;
    esac
    printf '%s\n' "$Expected" > "$Staging/$ArchiveMarker"
    mv "$Staging" "$Target"
    Staging=""
fi
if [ "$Unchanged" = 0 ]; then
    ln -sfn "versions/$Name" "$Prefix/current"
fi

# Keep the active and the previously active versions; a Core started before the upgrade may still use the latter.
# Different archives of one version count as different generations; reinstalling the active archive prunes nothing.
# 保留当前与上一个当前代际；升级前启动的 Core 可能仍在使用后者。
# 同一版本的不同归档属于不同代际；重装当前归档不清理任何代际。
if [ "$Previous" != "versions/$Name" ]; then
    for Entry in "$Prefix/versions"/*; do
        [ -e "$Entry" ] || continue
        Base=${Entry##*/}
        if [ "$Base" != "$Name" ] && [ "versions/$Base" != "$Previous" ]; then
            rm -rf "$Entry"
        fi
    done
fi

mkdir -p "$BinDir"
# write_launcher installs a tiny script that follows the current link, so upgrades never rewrite launchers' targets.
# write_launcher 安装跟随 current 链接的小脚本，升级时无需改写启动器目标。
write_launcher() {
    if [ -e "$BinDir/$1" ] && ! grep -F "$LauncherMarker" "$BinDir/$1" >/dev/null 2>&1; then
        printf 'Skipped %s: a file not created by this installer already exists.\n' "$BinDir/$1" >&2
        return 0
    fi
    printf '#!/bin/sh\n%s\nexec "%s/current/%s" "$@"\n' "$LauncherMarker" "$Prefix" "$2" > "$BinDir/$1.tmp"
    chmod 755 "$BinDir/$1.tmp"
    mv -f "$BinDir/$1.tmp" "$BinDir/$1"
}
write_launcher vulcan-code "$Desktop"
write_launcher vulcan-code-service "$Service"
write_launcher vulcan-tui "$Tui"

# A unit registered from this prefix still names the old version's real path; re-registering moves it to the new one.
# 从本前缀注册的单元仍指向旧版本真实路径；重新注册使其切换到新版本。
if [ "$Unchanged" = 0 ] && owns_unit; then
    "$Prefix/current/$Service" --install-user-service || fail "installed $Name, but re-registering the user service failed"
fi

if [ "$Os" = linux ]; then
    if [ "$BrowserDependencies" = 1 ]; then
        "$Prefix/current/$Service" --install-browser-dependencies || fail "installed $Name, but installing browser system packages failed"
    else
        printf 'The built-in browser needs system libraries once: vulcan-code-service --install-browser-dependencies (uses sudo).\n'
    fi
fi

if [ "$Unchanged" = 1 ]; then
    printf 'Already installed %s into %s; launchers were refreshed.\n' "$Name" "$Prefix"
else
    printf 'Installed %s into %s.\n' "$Name" "$Prefix"
fi
printf 'Commands: vulcan-code (desktop), vulcan-code-service --headless (WebUI service), vulcan-tui (terminal).\n'
case ":$PATH:" in
    *":$BinDir:"*) ;;
    *) printf 'Add %s to PATH to use these commands.\n' "$BinDir" ;;
esac
